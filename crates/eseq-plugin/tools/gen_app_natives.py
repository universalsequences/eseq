#!/usr/bin/env python3
"""Regenerate crates/eseq-plugin/src/app_natives.rs: every native the eseq app
registers on its Lisp runtime (`register_native("name", ...)` under
crates/sequencer/src). The plugin panel registers each as a no-op stub, so
factory UI code that touches app state (delete targets, step selection, ...)
degrades to nil instead of an UnknownVariable error that kills the whole
callback. Run after adding app natives: tools/gen_app_natives.py"""
import pathlib, re

root = pathlib.Path(__file__).resolve().parents[3]
names = set()
for path in (root / "crates/sequencer/src").rglob("*.rs"):
    names.update(re.findall(r'register_native\(\s*"([^"]+)"', path.read_text()))
out = root / "crates/eseq-plugin/src/app_natives.rs"
body = "\n".join(f'    "{n}",' for n in sorted(names))
out.write_text(
    "//! GENERATED by tools/gen_app_natives.py — the natives the eseq app\n"
    "//! registers on its Lisp runtime; the panel stubs each one.\n\n"
    f"pub const APP_NATIVES: &[&str] = &[\n{body}\n];\n"
)
print(f"{len(names)} natives -> {out}")

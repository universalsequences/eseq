#!/usr/bin/env python3
"""Generate content/effects/pin-matrix/{dsp,ui}.lisp.

The pin matrix is SOURCES x DESTS scalar params (`pin_<src>_<dst>`, 0..1),
because effects cannot bind host-editable tensor-params yet. Edit the tables
below and re-run; the module DSP lives in MODULES_DSP.
"""
import os
import re

# (id, label) — matrix rows, VCS3 order-ish: inputs, generators, processors.
SOURCES = [
    ("inl", "IN L"), ("inr", "IN R"),
    ("osc1", "OSC 1"), ("osc2", "OSC 2"), ("osc3", "OSC 3"), ("sh", "S&H"),
    ("noise", "NOISE"), ("filt", "FILTER"), ("ring", "RING"), ("fold", "FOLD"),
    ("shup", "SHIFT +"), ("shdn", "SHIFT -"), ("env", "ENV FOL"),
    ("trap", "TRAP"), ("vca", "VCA"), ("spring", "SPRING"),
]
# (id, label) — matrix columns.
DESTS = [
    ("outl", "OUT L"), ("outr", "OUT R"),
    ("filt", "FILT IN"), ("fcv", "FILT FREQ"),
    ("ringa", "RING A"), ("ringb", "RING B"),
    ("fold", "FOLD IN"), ("foldcv", "FOLD AMT"),
    ("shift", "SHIFT IN"), ("shcv", "SHIFT FREQ"),
    ("vca", "VCA IN"), ("spring", "SPRING IN"),
    ("o1cv", "OSC1 FREQ"), ("o2cv", "OSC2 FREQ"),
]
# Default patch: stereo input through the filter (slowly swept by OSC 3)
# into the spring, both to the outputs.
DEFAULT_PINS = {
    ("inl", "filt"): 0.7, ("inr", "filt"): 0.7,
    ("osc3", "fcv"): 0.25,
    ("filt", "outl"): 0.8, ("filt", "outr"): 0.8,
    ("filt", "spring"): 0.5,
    ("spring", "outl"): 0.45, ("spring", "outr"): 0.35,
}

HEADER = """\
; Pin Matrix — an EMS VCS3 / Synthi AKS used as an audio processor (Eno's
; Roxy-era trick), crossed with Juergen Haible's JH Matrix FX (Aphex Twin):
; Serge-style wave folder, SSB frequency shifter with up/down outputs,
; Eventide-style envelope follower, trapezoid envelope + VCA, spring tank.
;
; GENERATED by scripts/gen_pin_matrix_fx.py — edit that, not this file.
;
; Every module's output enters the matrix through a one-sample history cell,
; so any patch is legal, feedback loops included (that's the instrument).
; Rows are sources, columns are destinations; each pin is a 0..1 gain
; (the resistor-pin colour, continuously).
"""

MODULES_DSP = """
; ── modules ─────────────────────────────────────────────────────────

;; Macro args are substituted textually: an arg used twice must be bound
;; once first, or a chain of N calls compiles 2^N copies of its input.

; Niemitalo z^-2 allpass section: y = a2*(x + y[n-2]) - x[n-2].
(defmacro hb-section (x a2)
  (def xin x)
  (make-history x1)
  (make-history x2)
  (make-history y1)
  (make-history y2)
  (def px1 (read-history x1))
  (def px2 (read-history x2))
  (def py1 (read-history y1))
  (def py2 (read-history y2))
  (def y (- (* a2 (+ xin py2)) px2))
  (write-history x2 px1)
  (write-history x1 xin)
  (write-history y2 py1)
  (write-history y1 y)
  y)

; 90-degree allpass pair (8 sections, ~+-0.7 deg over 20 Hz..20 kHz at 44.1k).
(defmacro hilbert-i (x)
  (make-history d)
  (def a (hb-section (hb-section (hb-section (hb-section x 0.47940086558884) 0.87621849353931) 0.97659758950819) 0.99749925593555))
  (def prev (read-history d))
  (write-history d a)
  prev)
(defmacro hilbert-q (x)
  (hb-section (hb-section (hb-section (hb-section x 0.16175849836770) 0.73302893234149) 0.94534970032911) 0.99059915668453))

; Serge-ish wave multiplier: driven triangle fold, then tanh-rounded peaks.
; sym adds DC before folding for the even-harmonic asymmetry.
(defmacro serge-fold (x amt sym)
  (def g (+ 1 (* 9 amt)))
  (def tri (- 1 (abs (- (wrap (+ (* (+ x (* 0.5 sym)) g) 1) 0 4) 2))))
  (/ (tanh (* 1.6 tri)) 0.9217))

; Stretched (z^-4) first-order allpass: the spring's dispersion stage.
(defmacro spring-ap (x a)
  (make-history yh)
  (def xin x)
  (def xk (delay xin 4 @max-delay 16))
  (def yk (delay (read-history yh) 3 @max-delay 16))
  (def y (- (+ (* a xin) xk) (* a yk)))
  (write-history yh y)
  y)

(defmacro spring-chain (x a)
  (spring-ap (spring-ap (spring-ap (spring-ap (spring-ap (spring-ap
    (spring-ap (spring-ap (spring-ap (spring-ap (spring-ap (spring-ap x a) a) a) a) a) a) a) a) a) a) a) a))

; One dispersive loop: delay -> 24 stretched allpasses -> damping -> feedback.
(defmacro spring-loop (x loop_ms decay a)
  (make-history fb)
  (def drive (+ x (* decay (read-history fb))))
  (def disp (spring-chain (spring-chain drive a) a))
  (def looped (delay disp (* loop_ms (/ samplerate 1000)) @max-delay 8192))
  (def damped (svf looped 4200 0.6 0))
  (write-history fb (tanh damped))
  disp)

; VCS3-ish 18 dB/oct ladder: three saturating one-pole stages with tanh
; feedback around them. The k that puts the loop at unity gain at its
; 180-deg point grows with the cutoff (8.3 at 160 Hz, 13.8 at 2.5 kHz, 25 at
; 5 kHz); kneed fits that, so res ~0.9 is the onset at every cutoff. Above
; ~5 kHz the 180-deg point runs into Nyquist, so resonance fades out there.
; A tiny noise floor seeds the scream from silence.
(defmacro vcs3-filter (x cutoff res drive)
  (make-history h1)
  (make-history h2)
  (make-history h3)
  (def g (clip (- 1 (exp (/ (* -1 twopi cutoff) samplerate))) 0.0001 0.99))
  (def p1 (read-history h1))
  (def p2 (read-history h2))
  (def p3 (read-history h3))
  (def kneed (+ 8 (* 12 g) (* 60 g g)))
  (def k (* 1.1 res kneed (clip (/ (- 7000 cutoff) 3000) 0 1)))
  (def u (tanh (- (+ (* drive x) (* 0.00001 (- (noise) 0.5))) (* k p3))))
  (def y1 (write-history h1 (+ p1 (* g (- u p1)))))
  (def y2 (write-history h2 (+ p2 (* g (- (tanh y1) p2)))))
  (def y3 (write-history h3 (+ p3 (* g (- (tanh y2) p3)))))
  (* y3 (+ 1 (* 2 res))))

; Envelope follower (Eventide Instant Flanger flavour): rectify, AR smooth.
(defmacro follower (x att rel)
  (make-history e)
  (def prev (read-history e))
  (def r (abs x))
  (def ka (- 1 (exp (/ -1 (* att samplerate)))))
  (def kr (- 1 (exp (/ -1 (* rel samplerate)))))
  (def k (gswitch (gt r prev) ka kr))
  (write-history e (+ prev (* k (- r prev)))))

; VCS3 trapezoid: Attack / On / Decay / Off. mode 0 cycles; mode 1 fires
; once on each rising edge of `gate` and parks at zero.
(defmacro trapezoid (att on dec off mode gate)
  (make-history t)
  (make-history g)
  (def tp (read-history t))
  (def rise (and (gt gate 0.5) (lte (read-history g) 0.5)))
  (write-history g gate)
  (def period (+ att on dec off))
  (def shot (+ att on dec))
  (def step (/ 1 samplerate))
  (def cyc (wrap (+ tp step) 0 period))
  (def one (gswitch rise 0 (min (+ tp step) shot)))
  (write-history t (gswitch (gt mode 0.5) one cyc))
  (def up (clip (/ tp att) 0 1))
  (def down (clip (/ (- tp (+ att on)) dec) 0 1))
  (* up (- 1 down)))
"""

PARAMS = """
(param osc1_oct @default 3 @min -8 @max 8 @unit oct)
(param osc2_oct @default 1.5 @min -8 @max 8 @unit oct)
(param osc2_shape @default 0.5 @min 0 @max 1)
(param osc3_oct @default -5.5 @min -8 @max 8 @unit oct)
(param noise_col @default 0.5 @min 0 @max 1)
(param filt_oct @default 6 @min 0 @max 9.8 @unit oct)
(param filt_res @default 0.45 @min 0 @max 1)
(param filt_drive @default 0.3 @min 0 @max 1)
(param fold_amt @default 0.3 @min 0 @max 1)
(param fold_sym @default 0 @min -1 @max 1)
(param shift @default 0.25 @min -1 @max 1)
(param env_att @default 5 @min 0.5 @max 500 @unit ms)
(param env_rel @default 0.15 @min 0.005 @max 2 @unit s)
(param env_gain @default 4 @min 0 @max 16)
(param trap_att @default 0.05 @min 0.001 @max 4 @unit s)
(param trap_on @default 0.1 @min 0 @max 4 @unit s)
(param trap_dec @default 0.4 @min 0.001 @max 8 @unit s)
(param trap_off @default 0.5 @min 0 @max 8 @unit s)
(param trap_mode @default 0 @min 0 @max 1)
(param trap_thresh @default 0.25 @min 0 @max 1)
(param vca_init @default 0 @min 0 @max 1)
(param spring_decay @default 0.55 @min 0 @max 0.95)
(param spring_disp @default 0.6 @min 0.1 @max 0.85)
(param level @default 1 @min 0 @max 2)
(param mix @default 1 @min 0 @max 1)
"""


def lisp_num(v):
    return repr(float(v))


# Panel params are host modulation targets; each is read once through
# `(mod name)`, clamped to its range, and the DSP below uses the `m_` copy.
PARAM_RE = re.compile(r"\(param (\w+) (.*?)\)$", re.M)


def mod_params():
    """[(name, attrs, lo, hi)] for every panel param."""
    res = []
    for name, attrs in PARAM_RE.findall(PARAMS):
        lo = float(re.search(r"@min (\S+)", attrs).group(1))
        hi = float(re.search(r"@max (\S+)", attrs).group(1))
        res.append((name, attrs, lo, hi))
    return res


def use_modulated(text):
    for name, _, _, _ in mod_params():
        text = re.sub(rf"\b{name}\b", f"m_{name}", text)
    return text


def gen_dsp():
    out = [HEADER]
    out.append("(def in_l (in 1 @name left))\n(def in_r (in 2 @name right))")
    out.append("\n".join(f"(def mod{i} (in {i + 2} @name mod{i} @modulator {i}))" for i in range(1, 5)))
    out.append("\n; ── panel params (host-modulatable) ──")
    for name, attrs, lo, hi in mod_params():
        out.append(f"(param {name} {attrs} @mod true @mod-mode additive)")
    for name, _, lo, hi in mod_params():
        out.append(f"(def m_{name} (clip (mod {name}) {lisp_num(lo)} {lisp_num(hi)}))")
    out.append("; ── pins (row = source, column = destination) ──")
    for s, _ in SOURCES:
        for d, _ in DESTS:
            dv = DEFAULT_PINS.get((s, d), 0.0)
            out.append(f"(param pin_{s}_{d} @default {lisp_num(dv)} @min 0 @max 1)")
    out.append(MODULES_DSP)
    out.append("; ── the matrix: previous-sample module outputs ──")
    module_srcs = [s for s, _ in SOURCES if s not in ("inl", "inr")]
    for s in module_srcs:
        out.append(f"(make-history h_{s})")
    out.append("(def src_inl in_l)\n(def src_inr in_r)")
    for s in module_srcs:
        out.append(f"(def src_{s} (read-history h_{s}))")
    out.append("")
    for d, _ in DESTS:
        terms = " ".join(f"(* src_{s} pin_{s}_{d})" for s, _ in SOURCES)
        out.append(f"(def dst_{d} (+ {terms}))")
    out.append(use_modulated("""
; ── generators ──
(def f1 (clip (* 20 (pow 2 (+ osc1_oct (* 4 dst_o1cv)))) 0.01 18000))
(def ph1 (phasor f1))
(def osc1 (sin (* ph1 twopi)))

(def f2 (clip (* 20 (pow 2 (+ osc2_oct (* 4 dst_o2cv)))) 0.01 18000))
(def ph2 (phasor f2))
(def s2 (clip osc2_shape 0.01 0.99))
(def osc2 (- (* 2 (gswitch (lt ph2 s2) (/ ph2 s2) (/ (- 1 ph2) (- 1 s2)))) 1))

(def ph3 (phasor (* 20 (pow 2 osc3_oct))))
(def osc3 (triangle ph3))
(make-history ph3_prev)
(def wrap3 (lt ph3 (read-history ph3_prev)))
(write-history ph3_prev ph3)
(def raw_noise (noise))
(def sh (- (* 2 (latch raw_noise wrap3)) 1))
(def noise_sig (svf (- (* 2 raw_noise) 1) (* 20 (pow 2 (+ 5 (* 4.8 noise_col)))) 0.5 0))

; ── processors ──
(def cutoff (clip (* 20 (pow 2 (+ filt_oct (* 5 dst_fcv)))) 20 18000))
(def filt (tanh (vcs3-filter dst_filt cutoff filt_res (+ 1 (* 4 filt_drive)))))

(def ring (tanh (* 2 dst_ringa dst_ringb)))

(def fold (serge-fold dst_fold (clip (+ fold_amt dst_foldcv) 0 1) fold_sym))

(def sh_amt (clip (+ shift dst_shcv) -1 1))
(def sh_hz (* (sign sh_amt) (- (pow 5001 (abs sh_amt)) 1)))
(def sh_ph (* (phasor (abs sh_hz)) twopi))
(def sh_c (cos sh_ph))
(def sh_s (* (sign sh_hz) (sin sh_ph)))
(def hi (hilbert-i dst_shift))
(def hq (hilbert-q dst_shift))
(def shup (+ (* hi sh_c) (* hq sh_s)))
(def shdn (- (* hi sh_c) (* hq sh_s)))

(def envf (clip (* env_gain (follower (* 0.5 (+ in_l in_r)) (* 0.001 env_att) env_rel)) 0 1))

(def trap (trapezoid trap_att trap_on trap_dec trap_off trap_mode (gt envf trap_thresh)))
(def vca (tanh (* dst_vca (clip (+ vca_init trap) 0 1.5))))

(def spring_in (svf dst_spring 5000 0.7 0))
(def spring (tanh (* 2.2 (+ (spring-loop spring_in 37 spring_decay spring_disp)
                            (spring-loop spring_in 51 (* 0.94 spring_decay) (* 0.9 spring_disp))))))
"""))
    values = {
        "osc1": "osc1", "osc2": "osc2", "osc3": "osc3", "sh": "sh",
        "noise": "noise_sig", "filt": "filt", "ring": "ring", "fold": "fold",
        "shup": "shup", "shdn": "shdn", "env": "envf", "trap": "trap",
        "vca": "vca", "spring": "spring",
    }
    for s in module_srcs:
        out.append(f"(write-history h_{s} {values[s]})")
    out.append(use_modulated("""
; ── outputs: DC-blocked, soft-limited, dry/wet ──
(def wet_l (tanh (* level (biquad dst_outl 12 0.707 1 1))))
(def wet_r (tanh (* level (biquad dst_outr 12 0.707 1 1))))
(out (+ (* in_l (- 1 mix)) (* wet_l mix)) 1 @name left)
(out (+ (* in_r (- 1 mix)) (* wet_r mix)) 2 @name right)
"""))
    return "\n".join(out)


def gen_ui():
    rows, cols = len(SOURCES), len(DESTS)
    # Taller than the lego full height (8.18): the rack's device body has
    # room below the knob blocks.
    panel_w, panel_h = 27.0, 10.14
    matrix_h = 8.9
    row_h = matrix_h / rows
    matrix_w = 23.0
    col_w = matrix_w / cols
    # Column headers: a module row spanning its columns, then the jack row.
    top = [("OUT", 2), ("FILT", 2), ("RING", 2), ("FOLD", 2), ("SHIFT", 2),
           ("IN", 2), ("OSC", 2)]
    bottom = ["L", "R", "in", "frq", "A", "B", "in", "amt", "in", "frq", "vca", "spr", "1", "2"]
    assert sum(n for _, n in top) == len(DESTS) == len(bottom)
    ind = " " * 12
    return UI_TEMPLATE.format(
        rows=rows, cols=cols,
        pin_names=" ".join(f'"pin_{s}_{d}"' for s, _ in SOURCES for d, _ in DESTS),
        row_h=f"{row_h:.4f}", col_w=f"{col_w:.4f}",
        matrix_w=matrix_w, matrix_h=matrix_h, panel_w=panel_w, panel_h=panel_h,
        col_labels_top="\n".join(f'{ind}(pinmx-col-label "{t}" {n})' for t, n in top),
        col_labels_bottom="\n".join(f'{ind}(pinmx-col-label "{b}" 1)' for b in bottom),
        row_labels="\n".join(f'{ind}  (pinmx-row-label "{l}")' for _, l in SOURCES),
    )


UI_TEMPLATE = open(os.path.join(os.path.dirname(__file__), "gen_pin_matrix_fx_ui.lisp.in")).read() \
    if os.path.exists(os.path.join(os.path.dirname(__file__), "gen_pin_matrix_fx_ui.lisp.in")) else ""


if __name__ == "__main__":
    root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "content", "effects", "pin-matrix")
    with open(os.path.join(root, "dsp.lisp"), "w") as f:
        f.write(gen_dsp())
    if UI_TEMPLATE:
        with open(os.path.join(root, "ui.lisp"), "w") as f:
            f.write(gen_ui())
    print("wrote", os.path.normpath(root))

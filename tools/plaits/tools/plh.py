#!/usr/bin/env python3
"""Plaits port test harness.

Builds a standalone DGenLisp test instrument around one engine macro and
compares it against the original C++ engine (ref/plref, mode=engine).

    import plh
    t = plh.EngineTest("va", ["engines/va.lisp"], "(plaits-va bstart bphase rise high patched note timbre morph harmonics accent)")
    t.compare(engine=8, note=48, harmonics=0.3, timbre=0.5, morph=0.5)

The engine call must evaluate to (tuple out aux); it can use the driver's
names: bstart bphase rise high patched note timbre morph harmonics accent
(all block-latched), plus u0 (one uniform noise draw per sample).

Ref/port keys: seconds gate retrig note harmonics timbre morph accent trig
(+ note_end harmonics_end timbre_end morph_end sweeps) and any extra ref-only
keys (prosody, speed, env_shape). Extra port params can be declared with
extra_params=["(param foo @default 0 @min 0 @max 1)"] and set via port={...}.
"""
import os
import subprocess
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)                      # tools/plaits
# Data files live in the instrument folder (PLAITS_DATA overrides).
DATA = os.environ.get("PLAITS_DATA", os.path.join(os.path.dirname(os.path.dirname(ROOT)), "content", "instruments", "Synths", "Plaits", "data"))
REF = os.path.join(ROOT, "ref", "plref")
COMMON = os.path.join(ROOT, "lib", "common.lisp")
REPO = os.path.dirname(os.path.dirname(ROOT))
# Generated test instruments and reference renders live outside the repo.
WORK = os.environ.get("PLAITS_WORK", os.path.expanduser("~/.cache/eseq-plaits"))
sys.path.insert(0, os.path.join(REPO, "tools", "audition"))
os.environ.setdefault("ESEQ_DGENLISP_TOOL", REPO + "/crates/sequencer/tools/DGenLisp-macos-arm64")
os.environ.setdefault("ESEQ_DGEN_TOOLCHAIN_ROOT", REPO + "/crates/sequencer/tools/dgen-toolchain")
import audition as A  # noqa: E402

DRIVER_HEAD = """
(def gate_in (in 1 @name gate))
(def pitch_in (in 2 @name pitch))
(def velocity_in (in 3 @name velocity))
(def trigger_in (in 4 @name trigger))
(param seconds @default 2 @min 0 @max 600)
(param gate_s @default 1 @min -1 @max 600)
(param retrig @default 0 @min 0 @max 600)
(param trig_patched @default 1 @min 0 @max 1)
(param p_note @default 48 @min -128 @max 200)
(param p_note_end @default -1000 @min -1000 @max 200)
(param p_harmonics @default 0.5 @min 0 @max 1)
(param p_harmonics_end @default -1 @min -1 @max 1)
(param p_timbre @default 0.5 @min 0 @max 1)
(param p_timbre_end @default -1 @min -1 @max 1)
(param p_morph @default 0.5 @min 0 @max 1)
(param p_morph_end @default -1 @min -1 @max 1)
(param p_accent @default 0.8 @min 0 @max 1)
"""

DRIVER_BODY = """
(def pl_ref_tune 1.0026666756)
(make-history h_bp)
(def bphase (read-history h_bp))
(write-history h_bp (% (+ bphase 1) 12))
(def bstart (eq bphase 0))
(make-history h_n)
(def n_now (read-history h_n))
(write-history h_n (+ n_now 1))
(def total (* seconds 48000))
(def frac (/ n_now total))
(defmacro sweep (a b) (gswitch (lt b -0.5) a (+ a (* (- b a) frac))))
(def note (pl-hold (gswitch (lt p_note_end -999) p_note (+ p_note (* (- p_note_end p_note) frac))) bstart))
(def harmonics (pl-hold (sweep p_harmonics p_harmonics_end) bstart))
(def timbre (pl-hold (sweep p_timbre p_timbre_end) bstart))
(def morph (pl-hold (sweep p_morph p_morph_end) bstart))
(def accent p_accent)
(def t_s (/ n_now 48000))
(def t_r (gswitch (gt retrig 0) (- t_s (* retrig (floor (/ t_s (max retrig 0.000001))))) t_s))
(def g_now (* (gte gate_s 0) (lt t_r gate_s)))
(make-history h_prevg)
(def g_blk (pl-hold g_now bstart))
(def g_prev (pl-hold (read-history h_prevg) bstart))
(write-history h_prevg (gswitch bstart g_now (read-history h_prevg)))
(def patched trig_patched)
(def rise (* patched g_blk (- 1 g_prev)))
(def high (* patched g_blk))
(def u0 (noise))
"""


class EngineTest:
    def __init__(self, name, lisp_files, call, data_files=(), extra_params=(),
                 extra_defs="", workdir=None):
        self.dir = workdir or os.path.join(WORK, "tests", name)
        os.makedirs(self.dir, exist_ok=True)
        parts = [";; generated by plh.py\n", DRIVER_HEAD]
        parts += [p + "\n" for p in extra_params]
        parts.append(open(COMMON).read())
        parts.append(DRIVER_BODY)
        for f in lisp_files:
            parts.append(open(os.path.join(ROOT, f) if not os.path.isabs(f) else f).read())
        parts.append(extra_defs)
        parts.append(f"\n(def (eng_out eng_aux) {call})\n")
        parts.append("(out eng_out 1 @name left)\n(out eng_aux 2 @name right)\n")
        src = "".join(parts)
        for d in data_files:
            src_path = d if os.path.isabs(d) else os.path.join(DATA, os.path.basename(d))
            dst = os.path.join(self.dir, os.path.basename(d))
            if not os.path.exists(dst) or open(dst, "rb").read() != open(src_path, "rb").read():
                with open(src_path, "rb") as fi, open(dst, "wb") as fo:
                    fo.write(fi.read())
        with open(os.path.join(self.dir, "dsp.lisp"), "w") as f:
            f.write(src)
        self.inst = A.Instrument(self.dir)

    def ref(self, **kw):
        path = os.path.join(self.dir, "ref.raw")
        args = [REF, path, "mode=engine"] + [f"{k}={v}" for k, v in kw.items()]
        subprocess.run(args, check=True)
        return np.fromfile(path, dtype=np.float32).reshape(-1, 2)

    def port(self, port=None, **kw):
        m = {"seconds": "seconds", "gate": "gate_s", "retrig": "retrig", "trig": "trig_patched",
             "note": "p_note", "note_end": "p_note_end", "harmonics": "p_harmonics",
             "harmonics_end": "p_harmonics_end", "timbre": "p_timbre", "timbre_end": "p_timbre_end",
             "morph": "p_morph", "morph_end": "p_morph_end", "accent": "p_accent"}
        params = {m[k]: float(v) for k, v in kw.items() if k in m}
        params.update(port or {})
        y, _ = self.inst.render(float(kw.get("seconds", 2.0)), pitch=440.0, vel=1.0, params=params)
        return np.asarray(y, dtype=np.float32)

    def compare(self, label="", port=None, maxlag=4, wav=None, **kw):
        kw.setdefault("seconds", 2.0)
        r = self.ref(**{k: v for k, v in kw.items()})
        p = self.port(port=port, **kw)
        n = min(len(r), len(p))
        r, p = r[:n], p[:n]
        res = []
        for ch, nm in ((0, "out"), (1, "aux")):
            rr = float(np.sqrt(np.mean(r[:, ch] ** 2)))
            pr = float(np.sqrt(np.mean(p[:, ch] ** 2)))
            best = min(range(-maxlag, maxlag + 1),
                       key=lambda L: np.mean((np.roll(p[:, ch], L)[64:-64] - r[64:-64, ch]) ** 2))
            err = float(np.sqrt(np.mean((np.roll(p[:, ch], best)[64:-64] - r[64:-64, ch]) ** 2)))
            # early window (first 100 ms): free of slow phase drift
            e0 = slice(64, 4800)
            rr0 = float(np.sqrt(np.mean(r[e0, ch] ** 2)))
            err0 = float(np.sqrt(np.mean((np.roll(p[:, ch], best)[e0] - r[e0, ch]) ** 2)))
            res.append((nm, rr, pr, best, err / max(rr, 1e-9), err0 / max(rr0, 1e-9)))
        line = "  ".join(f"{nm}: ref {rr:.4f} port {pr:.4f} lag {lag:+d} err {e:.4f} err100ms {e0:.4f}"
                         for nm, rr, pr, lag, e, e0 in res)
        print(f"{label:24s} {line}", flush=True)
        if wav:
            import wave
            for tag, y in (("ref", r), ("port", p)):
                with wave.open(f"{wav}-{tag}.wav", "wb") as w:
                    w.setnchannels(2); w.setsampwidth(2); w.setframerate(48000)
                    w.writeframes((np.clip(y, -1, 1) * 32767).astype("<i2").tobytes())
        return r, p, res


    def cpu(self, seconds=10.0, **kw):
        """Fraction of one core this engine takes in real time (48 kHz)."""
        import time
        self.port(seconds=0.1, **kw)
        t0 = time.perf_counter()
        self.port(seconds=seconds, **kw)
        frac = (time.perf_counter() - t0) / seconds
        print(f"cpu: {100 * frac:.2f}% of a core")
        return frac

            b(f"(def y{i}v{v} (* {sine} amp{i}v{v}))")
            b(f"(def dst{i}v{v} (sx-fld R{i}v{v} 0.25 4))")
            b(f"(def kp{i}v{v} (- 1 (sx-fld R{i}v{v} 0.0625 2)))")

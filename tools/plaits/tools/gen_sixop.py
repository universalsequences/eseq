#!/usr/bin/env python3
"""Generate engines/sixop.lisp (Plaits six-op FM engine, engine2/six_op_engine.cc).

Run from $P: python3 tools/gen_sixop.py  (also regenerates the patch data).
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import sixop_patches as SP  # noqa: E402

C = SP.COLS


def col(row, name):
    return f"(peek sx_patch {row} {C[name]})"


HEADER = f""";; ======================================================================
;; Six-op FM engine (plaits/dsp/engine2/six_op_engine.cc + plaits/dsp/fm/*):
;; DX7 patches from syx_bank_0..2 (Plaits engines 2, 3, 4 = bank 0, 1, 2).
;; GENERATED by tools/gen_sixop.py -- edit the generator, not this file.
;;
;; (plaits-sixop bstart bphase rise high patched note timbre morph harmonics
;;               accent bank)  -> (tuple out aux), out == aux.
;; Extra arg `bank` (0..2, block-latched, may change at runtime): a change
;; unloads both voices like SixOpEngine::LoadUserData (silence until the next
;; trigger when patched).
;;
;; Structure (faithful to the C++):
;; - two fm::Voice<6> instances; a rising edge moves to the other voice and
;;   loads the HARMONICS-selected patch into it (the previous note rings on
;;   through its release).
;; - staggered rendering: each block one voice renders 24 samples (its
;;   control state -- envelopes, operator levels, frequencies -- is updated
;;   every 24 samples, voices alternate blocks). A voice whose patch was just
;;   loaded spends its next render on Setup() and outputs nothing (0.5 ms).
;;   Only one voice updates its control state per block, so the control path
;;   below is computed once for the rendering voice `rv` and committed to
;;   that voice's histories.
;; - routing is generic: per operator source (none / bus1 / bus2 / feedback),
;;   destination (out / bus1 / bus2) and additive flag read from the patch
;;   tensor, operators evaluated in DX7 order 6..1 every sample.
;; Patch tensor: row 0 = never-loaded LFO defaults, row 1 + bank*32 + patch.
;; ======================================================================
(def sx_patch (tensor @shape [{SP.NROW} {SP.NCOL}] @file "sixop_patches.json"))
(def sx_sine (tensor @shape [641 1] @file "lut_sine.json"))
(def sx_cube_root (tensor @shape [18 1] @file "sixop_cube_root.json"))

; fm::Pow2Fast<1>: 2^floor(x) * (1 + frac(x)).
(defmacro sx-p2f1 (x)
  (def e (floor x))
  (* (exp (* 0.69314718 e)) (+ 1 (- x e))))

; fm::Pow2Fast<2>.
(defmacro sx-p2f2 (x)
  (def e (floor x))
  (def f (- x e))
  (* (exp (* 0.69314718 e)) (+ 1 (* f (+ 0.6565 (* f 0.3435))))))

; Envelope::value() segment, operator envelopes (reshaped ascending segments).
(defmacro sx-seg-op (from to phase)
  (def asc (lt from to))
  (def f (gswitch asc (max 6.7 from) from))
  (def t (gswitch asc (max 6.7 to) to))
  (def p (gswitch asc (* phase (- 2.5 phase) 0.666667) phase))
  (+ (* p (- t f)) f))

(defmacro sx-seg-pitch (from to phase)
  (+ (* phase (- to from)) from))

; Envelope::value(stage, phase, start); start < -50 = PREVIOUS_LEVEL.
(defmacro sx-val-op (stage phase start l0 l1 l2 l3)
  (def from (gswitch (lt start -50) (selector (+ stage 1) l3 l0 l1 l2) start))
  (sx-seg-op from (selector (+ stage 1) l0 l1 l2 l3) phase))
(defmacro sx-val-pitch (stage phase start l0 l1 l2 l3)
  (def from (gswitch (lt start -50) (selector (+ stage 1) l3 l0 l1 l2) start))
  (sx-seg-pitch from (selector (+ stage 1) l0 l1 l2 l3) phase))

; Envelope::Render(gate, rate, ad_scale, release_scale) -> (stage phase start value).
(defmacro sx-env-op (st ph sv l0 l1 l2 l3 i0 i1 i2 i3 gate rate ad rr)
  (def is3 (eq st 3))
  (def trans (gswitch gate is3 (- 1 is3)))
  (def sv1 (gswitch trans (sx-val-op st ph sv l0 l1 l2 l3) sv))
  (def st1 (gswitch trans (gswitch gate 0 3) st))
  (def ph1 (gswitch trans 0 ph))
  (def ph2 (+ ph1 (* (selector (+ st1 1) i0 i1 i2 i3) rate (gswitch (eq st1 3) rr ad))))
  (def over (gte ph2 1))
  (def ph3 (gswitch over (gte st1 2) ph2))
  (def st3 (+ st1 (* over (lt st1 2))))
  (def sv3 (gswitch over -100 sv1))
  (tuple st3 ph3 sv3 (sx-val-op st3 ph3 sv3 l0 l1 l2 l3)))
(defmacro sx-env-pitch (st ph sv l0 l1 l2 l3 i0 i1 i2 i3 gate rate ad rr)
  (def is3 (eq st 3))
  (def trans (gswitch gate is3 (- 1 is3)))
  (def sv1 (gswitch trans (sx-val-pitch st ph sv l0 l1 l2 l3) sv))
  (def st1 (gswitch trans (gswitch gate 0 3) st))
  (def ph1 (gswitch trans 0 ph))
  (def ph2 (+ ph1 (* (selector (+ st1 1) i0 i1 i2 i3) rate (gswitch (eq st1 3) rr ad))))
  (def over (gte ph2 1))
  (def ph3 (gswitch over (gte st1 2) ph2))
  (def st3 (+ st1 (* over (lt st1 2))))
  (def sv3 (gswitch over -100 sv1))
  (tuple st3 ph3 sv3 (sx-val-pitch st3 ph3 sv3 l0 l1 l2 l3)))

; Envelope::RenderAtSample(t, gate_duration) for 0 <= t <= gate_duration
; (always the case: t = gate_duration * morph).
(defmacro sx-ras-op (t l0 l1 l2 l3 i0 i1 i2 d0 d1 d2)
  (def t1 (- t d0))
  (def t2 (- t1 d1))
  (gswitch (lt t d0) (sx-seg-op l3 l0 (* t i0))
    (gswitch (lt t1 d1) (sx-seg-op l0 l1 (* t1 i1))
      (gswitch (lt (- t2 d2) 0) (sx-seg-op l1 l2 (* t2 i2)) l2))))
(defmacro sx-ras-pitch (t l0 l1 l2 l3 i0 i1 i2 d0 d1 d2)
  (def t1 (- t d0))
  (def t2 (- t1 d1))
  (gswitch (lt t d0) (sx-seg-pitch l3 l0 (* t i0))
    (gswitch (lt t1 d1) (sx-seg-pitch l0 l1 (* t1 i1))
      (gswitch (lt (- t2 d2) 0) (sx-seg-pitch l1 l2 (* t2 i2)) l2))))

; plaits SinePM(phase, pm): pm in cycles quantized like float(pm + 32),
; 512-point lut_sine with linear interpolation.
(defmacro sx-sinepm (ph pm)
  (def pq (* (- (floor (+ (* (+ pm 32) 262144) 0.5)) 8388608) 0.000003814697265625))
  (def x (* (pl-wrap (+ ph pq)) 512))
  (def i (floor x))
  (def a (peek sx_sine i 0))
  (+ a (* (- (peek sx_sine (+ i 1) 0) a) (- x i))))

; Unsigned bit field of a packed integer c: floor(c / 2^shift) mod m
; (inv = 2^-shift, m a power of 2; exact in float32).
(defmacro sx-fld (c inv m)
  (def q (floor (* c inv)))
  (- q (* m (floor (/ q m)))))

; fm::KeyboardScaling.
(defmacro sx-kbs (note bp ld rd lc rc)
  (def x (- note bp 15))
  (def pos (gt x 0))
  (def curve (gswitch pos rc lc))
  (def t (abs x))
  (def tc (min (* t 0.010467) 1))
  (def t2 (gswitch (* (gte curve 1) (lte curve 2)) (* tc tc tc 96) t))
  (* (gswitch (lt curve 2) (- 0 t2) t2) (gswitch pos rd ld) 0.02677))

; fm::NormalizeVelocity.
(defmacro sx-norm-vel (v)
  (def x (* (clip v 0 1) 16))
  (def i (floor x))
  (def a (peek sx_cube_root i 0))
  (def b (peek sx_cube_root (+ i 1) 0))
  (* 16 (- (+ a (* (- b a) (- x i))) 0.918)))

; fm::Lfo::value().
(defmacro sx-lfo-val (ph rnd wave)
  (selector (+ wave 1)
    (* 2 (gswitch (lt ph 0.5) (- 0.5 ph) (- ph 0.5)))
    (- 1 ph)
    ph
    (gte ph 0.5)
    (- 0.5 (* 0.5 (sin (* twopi ph))))
    rnd))

; fm::Lfo::Step(12) -> (phase delay_phase random value).
(defmacro sx-lfo-step (ph dp rnd row u)
  (def ph1 (+ ph (* 12 {col('row', 'lfo_freq')})))
  (def wr (gte ph1 1))
  (def ph2 (- ph1 wr))
  (def rnd2 (gswitch wr u rnd))
  (def dp2 (min 1 (+ dp (* 12 (gswitch (lt dp 0.5) {col('row', 'lfo_di0')} {col('row', 'lfo_di1')})))))
  (tuple ph2 dp2 rnd2 (sx-lfo-val ph2 rnd2 {col('row', 'lfo_wave')})))

; a0 * 0.25 * SemitonesToRatioSafe(semi) in cycles/sample (no clamping: the
; pitch envelope / LFO can push far beyond the pl-note-to-freq range).
(defmacro sx-semi-freq (semi)
  (def k (- (max 0 (ceil (/ (- semi 120) 120))) (max 0 (ceil (/ (- -120 semi) 120)))))
  (* (/ 13.75 samplerate) pl_ref_tune (exp (* 6.93147181 k)) (pl-semi-ratio (- semi (* 120 k)))))

(defmacro sx-lfo-ramp (dp)
  (gswitch (lt dp 0.5) 0 (* (- dp 0.5) 2)))
"""


class Body:
    def __init__(self):
        self.lines = []
        self.states = []

    def __call__(self, s):
        self.lines.append("  " + s)

    def state(self, name, init=0.0):
        self.states.append((name, init))
        self(f"(make-history h_{name})")
        if init:
            self(f"(def {name}_o (+ (read-history h_{name}) {init}))")
        else:
            self(f"(def {name}_o (read-history h_{name}))")

    def writes(self):
        for name, init in self.states:
            if init:
                self(f"(write-history h_{name} (- {name} {init}))")
            else:
                self(f"(write-history h_{name} {name})")


# The exact SinePM emulation (lut_sine, 512 points) costs ~1.5% of a core
# more than `sin` and only changes results by ~1e-5 (visible only in chaotic
# feedback-7 patches), so `sin` is the default (SX_LUT=1 for the exact one).

def gen():
    b = Body()
    ENV_GD = 1.5 * 47872.34
    b("; ---- SixOpEngine::Render block logic (committed on bstart) ----")
    b("(def sx_u (noise))  ; S&H LFO draws (stmlib::Random in the C++)")
    b.state("rv")
    b("(def rv (gswitch bstart (- 1 rv_o) rv_o))")
    b("; HysteresisQuantizer2(32, 0.005, false) on harmonics * 1.02")
    b.state("q")
    b("(def q_v (- (* harmonics 1.02 32) 0.5))")
    b("(def q (gswitch bstart (clip (floor (+ q_v (gswitch (gt q_v q_o) -0.005 0.005) 0.5)) 0 31) q_o))")
    b.state("bk")
    b("(def bk_in (clip (floor (+ bank 0.5)) 0 2))")
    b("(def bchg (* bstart (- 1 (eq bk_in bk_o))))")
    b("(def bk (gswitch bstart bk_in bk_o))")
    b("(def key (+ 1 (* bk 32) q))")
    b("(def unp (- 1 patched))")
    b.state("act", 1)
    b("(def act_p (gswitch rise (- 1 act_o) act_o))")
    b("(def act (gswitch bstart (gswitch patched act_p act_o) act_o))")
    for v in (0, 1):
        b.state(f"ld{v}")
        b.state(f"row{v}")
        b.state(f"dl{v}")  # dirty
        b.state(f"nt{v}", 48)
        b.state(f"vl{v}", 0.5)
        b.state(f"ec{v}", 0.5)
        b.state(f"lph{v}")
        b.state(f"ldp{v}")
        b.state(f"lrn{v}")
        b.state(f"lvl{v}")
    b.state("lpi0")
    for v in (0, 1):
        b(f"(def ld{v}a (* ld{v}_o (- 1 bchg)))")
        b(f"(def same{v} (* ld{v}a (eq row{v}_o key)))")
        b(f"(def load{v} (* rise (eq act_p {v})))")
        # patched / unpatched load
        b(f"(def ldp_{v} (gswitch patched (max ld{v}a load{v}) 1))")
        b(f"(def rowp_{v} (gswitch patched (gswitch load{v} key row{v}_o) key))")
        b(f"(def dlp_{v} (max dl{v}_o (* (gswitch patched load{v} 1) (- 1 same{v}))))")
        b(f"(def ld{v} (gswitch bstart ldp_{v} ld{v}_o))")
        b(f"(def row{v} (gswitch bstart rowp_{v} row{v}_o))")
        b(f"(def dll{v} (gswitch bstart dlp_{v} dl{v}_o))")
        b(f"(def setp{v} (* bstart (max unp (eq act {v}))))")
        b(f"(def nt{v} (gswitch setp{v} note nt{v}_o))")
        b(f"(def vl{v} (gswitch setp{v} accent vl{v}_o))")
        b(f"(def ec{v} (gswitch setp{v} morph ec{v}_o))")
    b("; LFOs. Patched: active voice resets on rise and steps; the other steps")
    b("; only when its patch differs. Unpatched: voice 0 LFO is scrubbed by MORPH.")
    b("(def ld_a (gswitch act ld1 ld0))")
    b("(def row_a (gswitch act row1 row0))")
    for v in (0, 1):
        u = "sx_u" if v == 0 else "(pl-noise-tap sx_u)"
        b(f"(def samep{v} (* (eq ld{v} ld_a) (max (- 1 ld{v}) (eq row{v} row_a))))")
        b(f"(def stp{v} (max (eq act {v}) (- 1 samep{v})))")
        b(f"(def rsl{v} (* load{v} {col(f'row{v}', 'lfo_reset')}))")
        b(f"(def lph{v}r (gswitch rsl{v} 0 lph{v}_o))")
        b(f"(def ldp{v}r (gswitch load{v} 0 ldp{v}_o))")
        b(f"(def (lph{v}s ldp{v}s lrn{v}s lvl{v}s) (sx-lfo-step lph{v}r ldp{v}r lrn{v}_o row{v} {u}))")
        b(f"(def lph{v}p (gswitch stp{v} lph{v}s lph{v}r))")
        b(f"(def ldp{v}p (gswitch stp{v} ldp{v}s ldp{v}r))")
        b(f"(def lrn{v}p (gswitch stp{v} lrn{v}s lrn{v}_o))")
        b(f"(def lvl{v}p (gswitch stp{v} lvl{v}s lvl{v}_o))")
    b("; Lfo::Scrub(2 * kCorrectedSampleRate * morph) with the pre-load patch")
    b("(def scs (* 2 47872.34 morph))")
    b(f"(def scph (* scs {col('row0_o', 'lfo_freq')}))")
    b("(def scpi (floor scph))")
    b("(def scfr (- scph scpi))")
    b("(def scnew (- 1 (eq scpi lpi0_o)))")
    b("(def scrn (gswitch scnew sx_u lrn0_o))")
    b(f"(def scdi0 {col('row0_o', 'lfo_di0')})")
    b("(def scdp0 (* scs scdi0))")
    b(f"(def scdp (gswitch (gt scdp0 0.5) (min 1 (+ 0.5 (* (- scs (/ 0.5 (max scdi0 0.000000001))) {col('row0_o', 'lfo_di1')}))) scdp0))")
    b(f"(def scvl (sx-lfo-val scfr scrn {col('row0_o', 'lfo_wave')}))")
    b("(def sp0 (* bstart unp))")
    b("(def lpi0 (gswitch sp0 scpi lpi0_o))")
    b("(def lph0 (gswitch bstart (gswitch patched lph0p scfr) lph0_o))")
    b("(def ldp0 (gswitch bstart (gswitch patched ldp0p scdp) ldp0_o))")
    b("(def lrn0 (gswitch bstart (gswitch patched lrn0p scrn) lrn0_o))")
    b("(def lvl0 (gswitch bstart (gswitch patched lvl0p scvl) lvl0_o))")
    b("(def lph1 (gswitch bstart (gswitch patched lph1p lph1_o) lph1_o))")
    b("(def ldp1 (gswitch bstart (gswitch patched ldp1p ldp1_o) ldp1_o))")
    b("(def lrn1 (gswitch bstart (gswitch patched lrn1p lrn1_o) lrn1_o))")
    b("(def lvl1 (gswitch bstart (gswitch patched lvl1p lvl1_o) lvl1_o))")

    b("; ---- control path for the rendering voice s = rv ----")
    b("(def ld_s (gswitch rv ld1 ld0))")
    b("(def dl_s (gswitch rv dll1 dll0))")
    b("(def row_s (gswitch rv row1 row0))")
    b("(def full (* ld_s (- 1 dl_s)))")
    b("(def rs0 (* bstart (eq rv 0)))")
    b("(def rs1 (* bstart (eq rv 1)))")
    b("(def dl0 (* dll0 (- 1 (* rs0 ld0))))")
    b("(def dl1 (* dll1 (- 1 (* rs1 ld1))))")
    b("(def gate_s (* patched high (eq act rv)))")
    b("(def sus_s (* unp (eq rv 0)))")
    b("(def note_s (gswitch rv nt1 nt0))")
    b("(def vel_s (gswitch rv vl1 vl0))")
    b("(def ec_s (gswitch rv ec1 ec0))")
    b("; set_modulations: source LFO")
    b("(def msrc (gswitch patched (gswitch (gswitch rv samep1 samep0) act rv) 0))")
    b("(def m_val (gswitch msrc lvl1 lvl0))")
    b("(def m_ramp (sx-lfo-ramp (gswitch msrc ldp1 ldp0)))")
    b("(def m_row (gswitch msrc row1 row0))")
    b(f"(def pm_s (* (- m_val 0.5) m_ramp {col('m_row', 'lfo_pmd')}))")
    b(f"(def am_s (* (- 1 m_val) m_ramp {col('m_row', 'lfo_amd')}))")
    b("; voice-internal state")
    for v in (0, 1):
        b.state(f"gi{v}")
        b.state(f"ni{v}", 48)
        b.state(f"nv{v}", 10)
        b.state(f"pst{v}", 3)
        b.state(f"pph{v}", 1)
        b.state(f"psv{v}")
        for i in range(6):
            b.state(f"o{i}st{v}", 3)
            b.state(f"o{i}ph{v}", 1)
            b.state(f"o{i}sv{v}")
            b.state(f"T{i}v{v}")
    b("(def ad (sx-p2f1 (* (- 0.5 ec_s) 8)))")
    b("(def rr (sx-p2f1 (* (abs (- ec_s 0.3)) -8)))")
    b(f"(def es (* {ENV_GD} ec_s))")
    pl = " ".join(col("row_s", f"pl{j}") for j in range(4))
    pi = " ".join(f"pi{j}" for j in range(4))
    for j in range(4):
        b(f"(def pi{j} {col('row_s', f'pi{j}')})")
    pd = " ".join(f"(/ 1 pi{j})" for j in range(3))
    pi3 = " ".join(f"pi{j}" for j in range(3))
    b(f"(def (pst_n pph_n psv_n pv_r) (sx-env-pitch (gswitch rv pst1_o pst0_o) (gswitch rv pph1_o pph0_o) (gswitch rv psv1_o psv0_o) {pl} {pi} gate_s 24 ad rr))")
    b(f"(def pv_a (sx-ras-pitch es {pl} {pi3} {pd}))")
    b("(def penv (gswitch sus_s pv_a pv_r))")
    b("(def fbase (sx-semi-freq (+ (- note_s 9) (* 12 (+ penv pm_s)))))")
    b("(def ohz (/ pl_ref_tune samplerate))")
    b("(def gi_s (gswitch rv gi1_o gi0_o))")
    b("(def note_on (* gate_s (- 1 gi_s)))")
    b("(def upd (max note_on sus_s))")
    b("(def nv_n (gswitch upd (sx-norm-vel vel_s) (gswitch rv nv1_o nv0_o)))")
    b("(def ni_n (gswitch upd note_s (gswitch rv ni1_o ni0_o)))")
    b(f"(def rst (* note_on {col('row_s', 'reset_phase')}))")
    b("(def brt (* (- timbre 0.5) 32))")
    b("(def kbn (- (* ni_n 0.33333) 7))")
    for i in range(6):
        k = lambda n: col("row_s", f"o{i}_{n}")
        ol = " ".join(k(f"l{j}") for j in range(4))
        for j in range(4):
            b(f"(def o{i}i{j} {k(f'i{j}')})")
        oi = " ".join(f"o{i}i{j}" for j in range(4))
        oi3 = " ".join(f"o{i}i{j}" for j in range(3))
        od = " ".join(f"(/ 1 o{i}i{j})" for j in range(3))
        b(f"(def kc{i} {k('kc')})")
        b(f"(def kb{i} {k('kb')})")
        b(f"; operator {6 - i}")
        b(f"(def ra{i} {k('ratio')})")
        b(f"(def f{i} (min 0.5 (gswitch (gt ra{i} 0) (* ra{i} fbase) (* (- 0 ra{i}) ohz))))")
        b(f"(def fi{i} (floor (* f{i} 4294967296)))")
        b(f"(def fhi{i} (floor (* fi{i} 0.0000152587890625)))")
        b(f"(def flo{i} (- fi{i} (* fhi{i} 65536)))")
        b(f"(def rsc{i} (sx-p2f1 (* (sx-fld kc{i} 0.0625 8) kbn 0.03125)))")
        b(f"(def (o{i}st_n o{i}ph_n o{i}sv_n o{i}v_r) (sx-env-op (gswitch rv o{i}st1_o o{i}st0_o) (gswitch rv o{i}ph1_o o{i}ph0_o) (gswitch rv o{i}sv1_o o{i}sv0_o) {ol} {oi} gate_s (* 24 rsc{i}) ad rr))")
        b(f"(def o{i}v_a (sx-ras-op es {ol} {oi3} {od}))")
        b(f"(def lv{i} (+ (gswitch sus_s o{i}v_a o{i}v_r) (* 0.125 (min (+ (sx-kbs ni_n (sx-fld kb{i} 1 128) (sx-fld kb{i} 0.0078125 128) (sx-fld kb{i} 0.00006103515625 128) (sx-fld kc{i} 1 4) (sx-fld kc{i} 0.25 4)) (* nv_n (sx-fld kc{i} 0.0078125 8)) (* (sx-fld kc{i} 0.000244140625 2) brt)) {k('headroom')}))))")
        b(f"(def lm{i} (- 1 (sx-p2f2 (* 6.4 (- (* (selector (+ 1 (sx-fld kc{i} 0.0009765625 4)) 0 0.2588 0.4274 1) am_s) 1)))))")
        b(f"(def rt{i} {k('rt')})")
        b(f"(def a{i} (min 4 (sx-p2f2 (+ -14 (* lv{i} lm{i})))))")
    b(f"(def fbsc {col('row_s', 'fb_scale')})")
    b("; ---- commits of the control path ----")
    for v in (0, 1):
        b(f"(def cm{v} (* rs{v} full))")
        b(f"(def ce{v} (* cm{v} (- 1 sus_s)))")
        b(f"(def gi{v} (gswitch cm{v} gate_s gi{v}_o))")
        b(f"(def ni{v} (gswitch cm{v} ni_n ni{v}_o))")
        b(f"(def nv{v} (gswitch cm{v} nv_n nv{v}_o))")
        for nm in ("pst", "pph", "psv"):
            b(f"(def {nm}{v} (gswitch ce{v} {nm}_n {nm}{v}_o))")
        for i in range(6):
            for nm in ("st", "ph", "sv"):
                b(f"(def o{i}{nm}{v} (gswitch ce{v} o{i}{nm}_n o{i}{nm}{v}_o))")
    b("; ---- audio: both voices every sample ----")
    for v in (0, 1):
        b.state(f"fl{v}")
        b.state(f"FS{v}")
        b.state(f"fbp{v}")
        b.state(f"fbq{v}")
        for i in range(6):
            b.state(f"R{i}v{v}")
            b.state(f"fH{i}v{v}")
            b.state(f"fL{i}v{v}")
            b.state(f"pL{i}v{v}")
            b.state(f"A{i}v{v}")
            b.state(f"pH{i}v{v}")
    for v in (0, 1):
        b(f"(def fl{v} (gswitch rs{v} full fl{v}_o))")

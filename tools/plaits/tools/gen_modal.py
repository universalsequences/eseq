#!/usr/bin/env python3
"""Generates engines/modal.lisp (24 unrolled Resonator modes)."""
import os
import numpy as np

f = np.float32
# Resonator::Init(0.015, 24): CosineOscillator<APPROXIMATE>(0.015) * 0.25
freq = f(0.015) - f(0.25)
sign = f(16.0)
if freq < 0:
    freq = -freq
elif freq > 0.5:
    freq -= f(0.5)
else:
    sign = f(-16.0)
c = f(f(sign * freq) * f(f(1) - f(2) * freq))
y1, y0 = f(c * f(0.25)), f(0.5)
amps = []
for i in range(24):
    t = y0
    y0 = f(c * y0 - y1)
    y1 = t
    amps.append(f(f(t + f(0.5)) * f(0.25)))

N = 24
L = []
L.append("""; ======================================================================
; Modal engine (plaits/dsp/engine/modal_engine.cc): ModalVoice
; (physical_modelling/modal_voice.cc + resonator.cc). A bank of 24 bandpass
; SVF modes (stretched by lut_stiffness, Q falling with mode index) excited
; by a lowpassed impulse on trigger, or by continuous dust when the trigger
; input is unpatched. out = resonator, aux = excitation.
; Generated by tools/gen_modal.py -- edit that, not this file.
; Uses the driver's u0 (uniform [0,1)) for the dust exciter.
; ======================================================================
(def modal_lut_stiffness (tensor @shape [65 1] @file "lut_stiffness.json"))

; ResonatorSvf bandpass mode (stmlib OnePole::tan FAST); returns gain * bp.
(defmacro modal-mode (x f q gain)
  (make-history s1)
  (make-history s2)
  (def g (pl-tan-fast f))
  (def r (/ 1 q))
  (def h (/ 1 (+ 1 (* r g) (* g g))))
  (def st1 (read-history s1))
  (def st2 (read-history s2))
  (def hp (* (- x (* (+ r g) st1) st2) h))
  (def bp (+ (* g hp) st1))
  (def lp (+ (* g bp) st2))
  (write-history s1 (+ (* g hp) bp))
  (write-history s2 (+ (* g bp) lp))
  (* gain bp))

(defmacro plaits-modal (bstart bphase rise high patched note timbre morph harmonics accent)
  ; harmonics_lp_: ONE_POLE(.., harmonics, 0.01) once per block
  (make-history h_hlp)
  (def hlp_prev (read-history h_hlp))
  (def structure (gswitch bstart (+ hlp_prev (* 0.01 (- harmonics hlp_prev))) hlp_prev))
  (write-history h_hlp structure)
  (def f0 (pl-note-to-freq note))
  (def sus (- 1 patched))
  (def density (* timbre timbre))
  (def b (+ timbre (* 0.25 accent (- 1 timbre))))
  (def dmp (+ morph (* 0.25 accent (- 1 morph))))
  (def rng (gswitch sus 36 60))
  (def cutoff (min (* (gswitch sus 4 2) f0 (pl-semi-ratio (* (- (* b (- 2 b)) 0.5) rng))) 0.499))
  (def eq_ (gswitch sus 0.7 1.5))
  ; excitation: dust (sustain) or a single impulse on the trigger
  (def dust_f (+ 0.00005 (* 0.99995 density density)))
  (def dust (gswitch (lt u0 dust_f) (/ u0 dust_f) 0))
  (def amp (* (+ 0.12 (* 0.08 accent)) (- 1 (* dmp 0.5))))
  (def impulse (* bstart rise (/ (* amp (pl-semi-ratio (* cutoff cutoff 24))) cutoff)))
  (def exc (gswitch sus (* dust (- 4 (* dust_f 3)) accent) impulse))
  ; excitation_filter_: ResonatorSvf<1> low pass, gain 1
  (make-history e1)
  (make-history e2)
  (def eg (pl-tan-fast cutoff))
  (def er (/ 1 eq_))
  (def eh (/ 1 (+ 1 (* er eg) (* eg eg))))
  (def ee1 (read-history e1))
  (def ee2 (read-history e2))
  (def ehp (* (- exc (* (+ er eg) ee1) ee2) eh))
  (def ebp (+ (* eg ehp) ee1))
  (def elp (+ (* eg ebp) ee2))
  (write-history e1 (+ (* eg ehp) ebp))
  (write-history e2 (+ (* eg ebp) elp))
  ; Resonator::Process
  (def stiff0 (pl-lut modal_lut_stiffness structure 64))
  (def sk (gswitch (lt stiff0 0) 0.93 0.98))
  (def comp (/ 1 (+ 1 stiff0 (* stiff0 sk))))
  (def fc (* f0 comp))
  (def q_sqrt (pl-semi-ratio (* dmp 79.7)))
  (def q_0 (* 500 q_sqrt q_sqrt))
  (def rb (* b (- 1 (* structure 0.3)) (- 1 (* dmp 0.3))))
  (def q_loss (+ (* rb (- 2 rb) 0.85) 0.15))
  (def hm_0 fc)
  (def sf_0 1)""")
for i in range(N):
    L.append(f"  (def mf_{i} (min (* hm_{i} sf_{i}) 0.499))")
    L.append(f"  (def m_{i} (modal-mode elp mf_{i} (+ 1 (* mf_{i} q_{i})) (* {amps[i]:.9g} (- 1 (* mf_{i} 2)))))")
    if i < N - 1:
        L.append(f"  (def sf_{i+1} (+ sf_{i} stiff{i}))")
        L.append(f"  (def stiff{i+1} (* stiff{i} sk))")
        L.append(f"  (def hm_{i+1} (+ hm_{i} fc))")
        L.append(f"  (def q_{i+1} (* q_{i} q_loss))")
L.append("  (tuple (+ " + " ".join(f"m_{i}" for i in range(N)) + ") elp))")
src = "\n".join(L) + "\n"
open(os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "engines", "modal.lisp"), "w").write(src)
print("wrote engines/modal.lisp")

#!/usr/bin/env python3
"""Write content/ui/modal/drum-tables.lisp: a drum cavity's acoustic modes
and how each couples to the 120 modes of eseq.modal's circular membrane,
and the membrane's own shape table (for points fixed when generating).

The air in a cylinder with rigid walls (radius a, depth L) has pressure modes
    Psi = J_m(alpha r / a) cos(m theta) cos(l pi z / L)
with alpha a zero of J_m' (alpha = 0 for the uniform mode). A head on either
end face drives a mode by the overlap of its own shape with Psi there:
    g = (1 / pi a^2) * integral over the face of Psi * phi_k
which is zero unless the head mode and the air mode share m. This script
tabulates, per radial family (m, alpha): alpha, its mean square over the
face (lam), and its overlaps with every membrane mode of the same m, in the
membrane's own normalisation (content/defmacros/circ-membrane: mode shapes
N J_m(j r) cos(m theta) with mean square 1/2 over the head, sorted by
frequency). Everything is dimensionless (r over the radius), so one table
serves every drum; eseq.modal adds the axial index l and the drum's size.

Run from the repo root: python3 tools/modal/cavity_table.py
"""

import os
import re

import numpy as np

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
MACRO = os.path.join(REPO, "content", "defmacros", "circ-membrane", "macro.lisp")
OUT = os.path.join(REPO, "content", "ui", "modal", "drum-tables.lisp")
J01 = 2.404825557695773
ALPHA_MAX = 14.0  # air modes up to ~4.3 kHz across a 14" drum
TAU = np.linspace(0, np.pi, 2049)


def jn(m, x):
    """Bessel J_m(x) from (1/pi) int_0^pi cos(m tau - x sin tau) dtau."""
    x = np.atleast_1d(np.asarray(x, dtype=float))
    integrand = np.cos(m * TAU[None, :] - x[:, None] * np.sin(TAU[None, :]))
    return np.trapezoid(integrand, TAU, axis=1) / np.pi


def jnp(m, x):
    """J_m'(x) = (J_{m-1} - J_{m+1}) / 2."""
    return 0.5 * (jn(m - 1, x) - jn(m + 1, x)) if m > 0 else -jn(1, x)


def zeros(f, lo, hi, step=0.01):
    xs = np.arange(lo, hi, step)
    ys = f(xs)
    out = []
    for k in range(len(xs) - 1):
        if ys[k] == 0 or ys[k] * ys[k + 1] < 0:
            a, b = xs[k], xs[k + 1]
            for _ in range(60):
                c = 0.5 * (a + b)
                if f(a)[0] * f(c)[0] <= 0:
                    b = c
                else:
                    a = c
            out.append(0.5 * (a + b))
    return out


def membrane_modes():
    text = open(MACRO).read()
    def table(name):
        found = re.search(r"\(def " + name + r" \(tensor @shape \[\d+\] @data \[([^\]]*)\]", text)
        assert found, name
        return [float(v) for v in found.group(1).split()]
    ratios, ms = table("ratios"), table("m")
    return [(int(round(m)), r * J01) for m, r in zip(ms, ratios)], table("radial")


R = np.linspace(0, 1, 4001)


def radial_integral(f):
    return np.trapezoid(f * R, R)


def main():
    modes, radial = membrane_modes()
    norms = []
    for m, j in modes:
        shape = jn(m, j * R)
        mean_sq = (2 if m == 0 else 1) * radial_integral(shape ** 2)  # (1/pi) int int, cos^2 averaged
        norms.append(np.sqrt(0.5 / mean_sq))
    # check against the macro's tabulated value at r = 0 for the first mode
    assert abs(norms[0] * jn(0, 0.0)[0] - 1.36205) < 1e-3, norms[0]

    families = []
    for m in range(12):
        alphas = ([0.0] if m == 0 else []) + [a for a in zeros(lambda x: jnp(m, x), max(0.05, 0.9 * m), ALPHA_MAX) if a > 1e-6]
        # (J_m' > 0 below its first zero, which lies above m: starting there
        # skips the flat stretch near 0 where roundoff makes false zeros)
        for alpha in alphas:
            psi = jn(m, alpha * R)
            ang = 2.0 if m == 0 else 1.0
            lam = ang * radial_integral(psi ** 2)
            overlaps = []
            for k, (mk, j) in enumerate(modes):
                if mk != m:
                    continue
                g = ang * norms[k] * radial_integral(psi * jn(m, j * R))
                if abs(g) > 1e-4:
                    overlaps.append((k, g))
            families.append((m, alpha, lam, overlaps))
    families.sort(key=lambda fam: fam[1])

    lines = [
        ";; eseq.modal.drum-tables — GENERATED by tools/modal/cavity_table.py; do not edit.",
        ";;",
        ";; A drum cavity's acoustic modes' radial families, lowest first: each is",
        ";; (m alpha lam overlaps), the air mode J_m(alpha r) cos(m theta) (alpha a",
        ";; zero of J_m', 0 for the uniform mode), lam its mean square over the head,",
        ";; and overlaps a list of (k g): membrane mode k (circ-membrane's order) and",
        ";; the overlap g = (1/pi) * integral over the unit head of the air mode times",
        ";; the membrane mode. See eseq.modal's cavity.",
        ";;",
        ";; membrane-ratios, membrane-m and membrane-radial are circ-membrane's own",
        ";; tables (its modes' frequency ratios to the lowest, nodal diameters, and",
        ";; each mode's radial shape at r = 0, 0.1 .. 1), so a head of fewer modes",
        ";; and a point fixed when generating can be read without the macro.",
        "",
        "(module eseq.modal.drum-tables)",
        "",
        "(export families membrane-ratios membrane-m membrane-radial)",
        "",
        "(def membrane-ratios (list " + " ".join(f"{j / J01:.6f}" for _, j in modes) + "))",
        "",
        "(def membrane-m (list " + " ".join(str(m) for m, _ in modes) + "))",
        "",
        "(def membrane-radial",
        "  (list",
        *[ "    (list " + " ".join(f"{v:.5f}" for v in radial[11 * k:11 * k + 11]) + ")" for k in range(len(modes)) ],
        "  ))",
        "",
        "(def families",
        "  (list",
    ]
    for m, alpha, lam, overlaps in families:
        pairs = " ".join(f"(list {k} {g:.6f})" for k, g in overlaps)
        lines.append(f"    (list {m} {alpha:.6f} {lam:.6f} (list {pairs}))")
    lines.append("  ))")
    open(OUT, "w").write("\n".join(lines) + "\n")
    print(f"wrote {OUT}: {len(families)} families")
    for m, alpha, lam, overlaps in families[:8]:
        print(f"  m={m} alpha={alpha:.4f} lam={lam:.4f} overlaps={[(k, round(g, 3)) for k, g in overlaps[:4]]}")


if __name__ == "__main__":
    main()

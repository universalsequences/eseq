#!/usr/bin/env python3
"""Writes src/modal.lisp: the Rings modal resonator (rings/dsp/resonator.cc)
at polyphony 1, i.e. 60 bandpass modes (resolution 64 / 1 - 4)."""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
N = 60

head = f"""; ======================================================================
; Modal model (rings/dsp/part.cc RenderModalVoice + resonator.cc) at
; polyphony 1: a bank of {N} bandpass SVF modes, stretched by lut_stiffness,
; their Q falling with the mode index, excited by a lowpassed impulse on
; each strum. Odd modes go to `out`, even modes to `aux`, weighted by a
; cosine of POSITION (the pickup position along the bar).
; GENERATED by tools/gen_modal.py -- edit that, not this file.
; ======================================================================
(def modal_lut_stiffness (tensor @shape [257 1] @file "lut_stiffness.json"))
(def modal_lut_4_decades (tensor @shape [257 1] @file "lut_4_decades.json"))

; One stmlib Svf bandpass mode. With A = q-ish damping term (r = 1 / A),
; the coefficients are folded so each mode costs one division:
; h = A / D and (r + g) h = (1 + g A) / D with D = A (1 + g^2) + g.
(defmacro modal-mode (x g rgh h)
  (make-history s1)
  (make-history s2)
  (def st1 (read-history s1))
  (def st2 (read-history s2))
  (def hp (- (* x h) (* rgh st1) (* h st2)))
  (def bp (+ (* g hp) st1))
  (def lp (+ (* g bp) st2))
  (write-history s1 (+ (* g hp) bp))
  (write-history s2 (+ (* g bp) lp))
  bp)

; f0, structure, brightness, damping, position are block-latched.
(defmacro rg-modal (bstart bphase strum f0 structure brightness damping position)
  ; ---- excitation: impulse on the strum, through the excitation filter
  (def cutoff (* brightness (- 2 brightness)))
  (def fc (min (* f0 (rg-semi-ratio (* (- cutoff 0.5) 96))) 0.499))
  (def impulse (* bstart strum (/ (* 0.25 (rg-semi-ratio (* fc fc 24))) fc)))
  (def (exc_lp exc_bp exc_hp) (rg-svf impulse (rg-tan-dirty fc) 0.6666667))
  (def x (* exc_lp 0.125))
  ; ---- Resonator::ComputeFilters (block rate)
  (def stiff0 (rg-lut modal_lut_stiffness structure 256))
  (def kst (gswitch (lt stiff0 0) 0.93 0.98))
  (def q0 (* 500 (rg-lut modal_lut_4_decades damping 256)))
  (def ba2 (* (- 1 structure) (- 1 structure)))
  (def ba4 (* ba2 ba2))
  (def bright (* brightness brightness (- 1 (* 0.2 ba4 ba4))))
  (def ql0 (+ (* bright (- 2 bright) 0.85) 0.15))
  (def qrate (* structure (- 2 structure) 0.1))
"""

body = []
for i in range(N):
    if i == 0:
        body.append("  (def st0 stiff0)\n  (def sf0 1)\n  (def q_0 q0)\n  (def ql_0 ql0)")
    else:
        body.append(f"  (def sf{i} (+ sf{i-1} st{i-1}))")
        body.append(f"  (def st{i} (* st{i-1} kst))")
        body.append(f"  (def ql_{i} (+ ql_{i-1} (* qrate (- 1 ql_{i-1}))))")
        body.append(f"  (def q_{i} (* q_{i-1} ql_{i}))")
    body.append(f"  (def pr{i} (* f0 {i+1} sf{i}))")
    body.append(f"  (def pf{i} (min pr{i} 0.49))")
    body.append(f"  (def g{i} (rg-tan-fast pf{i}))")
    body.append(f"  (def a{i} (+ 1 (* pf{i} q_{i})))")
    body.append(f"  (def id{i} (/ 1 (+ (* a{i} (+ 1 (* g{i} g{i}))) g{i})))")
    body.append(f"  (def h{i} (* a{i} id{i}))")
    body.append(f"  (def rg{i} (* (+ 1 (* g{i} a{i})) id{i}))")
# num_modes = (last i with partial < 0.49) + 1; modes run in pairs.
nm = "0"
for i in range(N):
    nm = f"(max {nm} (* {i+1} (lt pr{i} 0.49)))" if i else f"(lt pr0 0.49)"
body.append(f"  (def nm {nm})")
for p in range(N // 2):
    body.append(f"  (def on{p} (lt {2*p} nm))")
body.append("""  ; ---- Resonator::Process: cosine amplitudes from the interpolated position
  (def pos (rg-interp position bstart bphase 0))
  (def c (rg-cos-coef pos))
  (def y_m1 (* c 0.25))
  (def y_0 0.5)""")
for k in range(1, N):
    prev2 = "y_m1" if k == 1 else f"y_{k-2}"
    body.append(f"  (def y_{k} (- (* c y_{k-1}) {prev2}))")
odd, even = [], []
for i in range(N):
    p = i // 2
    term = f"(* (+ y_{i} 0.5) (modal-mode (* x on{p}) g{i} rg{i} h{i}))"
    (odd if i % 2 == 0 else even).append(term)
body.append("  (def odd (* (+ " + "\n    ".join(f"(* on{i//2} {t})" if False else t for i, t in zip(range(0, N, 2), odd)) + ") 1))")
body.append("  (def even (+ " + "\n    ".join(even) + "))")
# outputs of inactive pairs are masked
body.append("  (tuple odd even))")
src = head + "\n".join(body) + "\n"
# mask outputs of inactive modes: multiply mode output by its pair flag
src = src.replace("(modal-mode (* x on", "(modal-mode-on (* x on")
src = src.replace("(defmacro rg-modal", """; Mode output masked when its pair is not processed (partials above 0.49).
(defmacro modal-mode-on (x g rgh h on)
  (* on (modal-mode x g rgh h)))

(defmacro rg-modal""")
import re
src = re.sub(r"\(modal-mode-on \(\* x on(\d+)\) g(\d+) rg(\d+) h(\d+)\)",
             lambda m: f"(modal-mode-on (* x on{m.group(1)}) g{m.group(2)} rg{m.group(3)} h{m.group(4)} on{m.group(1)})", src)
open(os.path.join(ROOT, "src", "modal.lisp"), "w").write(src)
print("wrote src/modal.lisp", len(src))

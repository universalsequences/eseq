#!/usr/bin/env python3
"""Writes src/tables.lisp: the chord tables (rings/dsp/part.cc and
string_synth_part.cc, BRYAN_CHORDS as dsp.h defines it, polyphony 1 rows),
the string synth registrations and the formant table, parsed from the
eurorack sources."""
import os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DSP = os.path.join(os.environ["EURORACK"], "rings", "dsp")


def bryan_block(src):
    m = re.search(r"#ifdef BRYAN_CHORDS(.*?)#else", src, re.S)
    assert m, "BRYAN_CHORDS block"
    assert re.search(r"^#define BRYAN_CHORDS", open(os.path.join(DSP, "dsp.h")).read(), re.M)
    return m.group(1)


def rows_of_first_group(block):
    # The table is {{poly 1 rows}, {poly 2 rows}, ...}: take the first group.
    body = re.sub(r"//.*", "", block)
    body = body[body.index("{", body.index("=")) + 1:]
    depth, start = 0, None
    for i, ch in enumerate(body):
        if ch == "{":
            depth += 1
            if depth == 1:
                start = i
        elif ch == "}":
            depth -= 1
            if depth == 0:
                group = body[start:i + 1]
                break
    rows = re.findall(r"\{([^{}]*)\}", group)
    return [[float(v.rstrip("f")) for v in re.findall(r"-?\d+\.?\d*f?", r)] for r in rows]


def floats(name, src):
    m = re.search(re.escape(name) + r"[^=]*=\s*\{(.*?)\};", src, re.S)
    body = re.sub(r"//.*", "", m.group(1))
    return [float(v.rstrip("f")) for v in re.findall(r"-?\d+\.?\d*f?", body)]


def tensor(name, values, comment):
    vals = " ".join(repr(v).rstrip("0").rstrip(".") if v != int(v) else str(int(v)) for v in values)
    return f"; {comment}\n(def {name} (tensor @shape [{len(values)} 1] @data [{vals}]))\n"


part = open(os.path.join(DSP, "part.cc")).read()
ssp = open(os.path.join(DSP, "string_synth_part.cc")).read()
part_chords = rows_of_first_group(bryan_block(part))
ss_chords = rows_of_first_group(bryan_block(ssp))
assert len(part_chords) == 11 and all(len(r) == 8 for r in part_chords)
assert len(ss_chords) == 11 and all(len(r) == 8 for r in ss_chords)
reg = floats("registrations[kRegistrationTableSize][kNumHarmonics * 2]", ssp)
assert len(reg) == 66
form = floats("formants[kFormantTableSize][kNumFormants]", ssp)
assert len(form) == 15

out = ["; GENERATED by tools/gen_tables.py from rings/dsp (BRYAN_CHORDS, as\n"
       "; rings/dsp/dsp.h defines it); edit that script, not this file.\n"]
out.append(tensor("rg_part_chords", [v for r in part_chords for v in r],
                  "part.cc chords[0]: 11 chords x 8 strings (semitones), row-major"))
out.append(tensor("rg_ss_chords", [v for r in ss_chords for v in r],
                  "string_synth_part.cc chords[0]: 11 chords x 8 notes, row-major"))
out.append(tensor("rg_ss_registrations", reg,
                  "string_synth_part.cc registrations: 11 x (3 harmonics x square/saw)"))
out.append(tensor("rg_ss_formants", form, "string_synth_part.cc formants: 5 vowels x 3 (Hz)"))
open(os.path.join(ROOT, "src", "tables.lisp"), "w").write("".join(out))
print("wrote src/tables.lisp")

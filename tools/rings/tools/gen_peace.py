import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

src = """; GENERATED by tools/gen_peace.py -- edit that, not this file.
; ======================================================================
; Disastrous Peace (rings/dsp/string_synth_part.cc) at polyphony 1: each
; strum plays a chord of 8 notes (STRUCTURE picks one of 11 chords), each
; note a stack of 3 octave-spaced polyBLEP square/saw oscillators whose
; mix BRIGHTNESS registers (from a dark square to bright saws). DAMPING
; sets the AD envelope (decay below noon, attack and decay above, drone at
; the end). Odd chord notes go to `out`, even ones to `aux`. The formant
; filters (POSITION = vowel) are here; chorus, ensemble and reverb are in
; the voice's fx section.
; ======================================================================

; StringSynthOscillator::Render for one harmonic: `inc` cycles per sample
; (already interpolated for the fundamental), `gain`/`gain_saw` block
; targets interpolated over the block. `dark` = 1: DARK_SQUARE (integrated,
; the fundamental), 0: BRIGHT_SQUARE (high-passed). Oscillators at or above
; 0.25 cycles per sample are not rendered (their state is frozen).
(defmacro ss-osc (inc target_gain target_gain_saw run bstart bphase dark)
  (make-history h_ph)
  (make-history h_hi)
  (make-history h_ns)
  (make-history h_nsaw)
  (make-history h_fs)
  (make-history h_g0)
  (make-history h_g1)
  (make-history h_s0)
  (make-history h_s1)
  ; ParameterInterpolators for the two gains, advanced only while rendering
  (def g_prev (gswitch bstart (read-history h_g1) (read-history h_g0)))
  (def g_cur (gswitch bstart target_gain (read-history h_g1)))
  (def s_prev (gswitch bstart (read-history h_s1) (read-history h_s0)))
  (def s_cur (gswitch bstart target_gain_saw (read-history h_s1)))
  (def k (/ (+ bphase 1) 24))
  (def gain (+ g_prev (* (- g_cur g_prev) k)))
  (def gain_saw (+ s_prev (* (- s_cur s_prev) k)))
  (write-history h_g0 (gswitch run g_prev (read-history h_g0)))
  (write-history h_g1 (gswitch run g_cur (read-history h_g1)))
  (write-history h_s0 (gswitch run s_prev (read-history h_s0)))
  (write-history h_s1 (gswitch run s_cur (read-history h_s1)))
  ; polyBLEP square + saw
  (def this0 (read-history h_ns))
  (def this_saw0 (read-history h_nsaw))
  (def high0 (read-history h_hi))
  (def ph0 (+ (read-history h_ph) inc))
  (def up (* (- 1 high0) (gte ph0 0.5)))
  (def t_up (/ (- ph0 0.5) inc))
  (def this1 (+ this0 (* up (rg-this-blep t_up))))
  (def next1 (* up (rg-next-blep t_up)))
  (def wrap (gte ph0 1))
  (def ph (- ph0 wrap))
  (def t_w (/ ph inc))
  (def wa (* wrap (rg-this-blep t_w)))
  (def wb (* wrap (rg-next-blep t_w)))
  (def this2 (- this1 wa))
  (def next2 (- next1 wb))
  (def this_saw (- this_saw0 wa))
  (def next_saw (- 0 wb))
  (def high (gswitch wrap 0 (max high0 up)))
  (def next3 (+ next2 (gte ph 0.5)))
  (def next_saw2 (+ next_saw ph))
  (def coef (* inc 2))
  (def fs_prev (read-history h_fs))
  (def sq_in (gswitch dark (* 4 (- this2 0.5)) (- (* 2 this2) 1)))
  (def fs (+ fs_prev (* coef (- sq_in fs_prev))))
  (def sample (gswitch dark fs (* (- sq_in fs) 0.5)))
  (def saw (- (* 2 this_saw) 1))
  (write-history h_ph (gswitch run ph (read-history h_ph)))
  (write-history h_hi (gswitch run high high0))
  (write-history h_ns (gswitch run next3 this0))
  (write-history h_nsaw (gswitch run next_saw2 this_saw0))
  (write-history h_fs (gswitch run fs fs_prev))
  (* run (+ (* sample gain) (* saw gain_saw))))

; One chord note: StringSynthVoice<3> (fundamental + 2 octaves up, with
; the 12 kHz / 8 kHz harmonic rolloff). `f` is the block target; the
; fundamental interpolates its increment over the block.
(defmacro ss-voice (f amp a0 a1 a2 a3 a4 a5 bstart bphase)
  (make-history h_i0)
  (make-history h_i1)
  (def run0 (lt f 0.25))
  (def i_prev (+ 0.01 (gswitch bstart (read-history h_i1) (read-history h_i0))))
  (def i_cur (+ 0.01 (gswitch bstart (- f 0.01) (read-history h_i1))))
  (write-history h_i0 (gswitch run0 (- i_prev 0.01) (read-history h_i0)))
  (write-history h_i1 (gswitch run0 (- i_cur 0.01) (read-history h_i1)))
  (def inc0 (+ i_prev (* (- i_cur i_prev) (/ (+ bphase 1) 24))))
  (def f1 (* f 2))
  (def f2 (* f 4))
  (def r0 (gswitch (gte f 0.17) (- 1 (* (- f 0.17) 12.5)) 1))
  (def r1 (gswitch (gte f1 0.17) (- 1 (* (- f1 0.17) 12.5)) 1))
  (def r2 (gswitch (gte f2 0.17) (- 1 (* (- f2 0.17) 12.5)) 1))
  (+ (ss-osc inc0 (* amp a0 r0) (* amp a1) run0 bstart bphase 1)
     (ss-osc f1 (* amp a2 r1) (* amp a3) (lt f1 0.25) bstart bphase 0)
     (ss-osc f2 (* amp a4 r2) (* amp a5) (lt f2 0.25) bstart bphase 0)))

; StringSynthEnvelope in AD mode, one step per block; returns the value.
(defmacro ss-envelope (rising attack_rate decay_rate bstart)
  (make-history h_seg)
  (make-history h_ph)
  (make-history h_sv)
  (make-history h_val)
  (make-history h_ready)
  (def ready (read-history h_ready))
  (def seg_prev (gswitch ready (read-history h_seg) 2))
  (def ph_prev (read-history h_ph))
  (def adv (* (- 1 rising) (gte ph_prev 1)))
  (def seg (gswitch rising 0 (+ seg_prev adv)))
  (def sv (gswitch rising (gswitch (gte seg_prev 2) 0 (read-history h_val))
                  (gswitch adv (eq seg_prev 0) (read-history h_sv))))
  (def ph (* (- 1 (max rising adv)) ph_prev))
  (def done (gte seg 2))
  (def inc (gswitch done 0 (gswitch (eq seg 0) attack_rate decay_rate)))
  (def u (- 1 ph))
  (def u2 (* u u))
  (def t (gswitch (eq seg 1) (- 1 (* u2 u2)) ph))
  (def target (eq seg 0))
  (def value (gswitch done 0 (+ sv (* (- target sv) t))))
  (write-history h_ready (max ready 1))
  (write-history h_seg (gswitch bstart seg seg_prev))
  (write-history h_ph (gswitch bstart (+ ph inc) ph_prev))
  (write-history h_sv (gswitch bstart sv (read-history h_sv)))
  (write-history h_val (gswitch bstart value (read-history h_val)))
  (rg-hold value bstart))

; Disastrous Peace voice. tonic/chord/brightness/damping/position are
; block-latched; strum is the block's strum flag; fx 0..5 the FX type.
(defmacro rg-peace (bstart bphase strum tonic chord brightness damping position fx)
  ; ---- chord acquisition: the chord follows STRUCTURE except during the
  ; strum block and the 2 blocks after it
  (make-history h_acq)
  (make-history h_chord)
  (def acq (gswitch strum 2 (max (- (read-history h_acq) 1) 0)))
  (def busy (max strum (gt (read-history h_acq) 0)))
  (def gchord (gswitch busy (read-history h_chord) chord))
  (write-history h_acq (gswitch bstart acq (read-history h_acq)))
  (write-history h_chord (gswitch bstart gchord (read-history h_chord)))
  (def ch (rg-hold gchord bstart))
  ; ---- envelope (ProcessEnvelopes)
  (def attack (gswitch (lt damping 0.5) 0 (* (- damping 0.5) 2)))
  (def period (/ samplerate 24))
  (def attack_rate (/ 1 (* (rg-semi-ratio (* attack 96)) 0.005 period)))
  (def decay_rate (/ 1 (* (rg-semi-ratio (* damping 84)) 0.18 period)))
  (def drone (min (gswitch (lt damping 0.98) 0 (* (- damping 0.98) 55)) 1))
  (def env (ss-envelope strum attack_rate decay_rate bstart))
  (def env_v (+ env (* (- 1 env) drone)))
  ; ---- ComputeRegistration(env * 0.25, brightness)
  (def reg (* brightness 9.999))
  (def ri (floor reg))
  (def rf (- reg ri))
"""

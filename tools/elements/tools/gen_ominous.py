#!/usr/bin/env python3
"""Writes src/ominous.lisp: the Ominous easter-egg voice with its 8x
oversampled FM oscillators and the 101-tap polyphase downsampler unrolled.
The FIR coefficients are kDownsamplingFilter from elements/dsp/ominous_voice.cc."""
import os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(os.environ["EURORACK"], "elements", "dsp", "ominous_voice.cc")


def coefficients():
    src = open(SRC).read()
    m = re.search(r"kDownsamplingFilter\[\]\s*=\s*\{(.*?)\};", src, re.S)
    vals = [float(v.rstrip("f")) for v in re.findall(r"-?\d+\.\d+f", m.group(1))]
    assert len(vals) == 101, len(vals)
    return vals


HEAD = r'''; ======================================================================
; Ominous voice (elements/dsp/ominous_voice.cc), the module's easter egg:
; two FM oscillator pairs (carrier + feedback modulator) rendered 8x
; oversampled and decimated by a 101-tap FIR, each through a multimode SVF,
; a shared envelope VCA and a rotating "spatializer" panner.
; Knob roles: BLOW level / meta / timbre = osc 1 level / ratio / FM amount,
; STRIKE level / meta / timbre = osc 2 level / ratio / FM amount, BOW level
; = osc 2 detune, BOW timbre = feedback, contour = envelope, geometry =
; filter mode + Q, brightness = cut-off, damping = envelope -> filter amount,
; position = rotation speed and distance.
; Pure scalar DSP: the voice runs inside a block-gate, only when selected.
; Inputs: patch values (block), midi (note + modulation), strength, flags.
; Returns (tuple raw center sides).
; Host-rate rules: the oscillators run 8x the host rate with their pitch
; kept; the decimation filters are relative to the oversampled rate; the
; envelope, smoothers, the spatializer's rotation and its "behind" low-pass
; keep their times / cut-off.
; Generated by tools/gen_ominous.py -- edit that, not this file.
; ======================================================================
(def om_lut_sine (tensor @shape [4097 1] @file "lut_sine.json"))
(def om_lut_f_high (tensor @shape [256 1] @file "lut_midi_to_f_high.json"))
(def om_lut_f_low (tensor @shape [256 1] @file "lut_midi_to_f_low.json"))
(def om_lut_fm_quantizer (tensor @shape [129 1] @file "lut_fm_frequency_quantizer.json"))
(def om_lut_detune_quantizer (tensor @shape [65 1] @file "lut_detune_quantizer.json"))

; lut_midi_to_f_high[] * lut_midi_to_f_low[] after the module's
; 32768 + Clip16(int(midi * 256) - 20480) index (cycles per 32 kHz sample).
(defmacro om-midi-to-f (midi)
  (def p (+ 32768 (clip (- (el-trunc (* midi 256)) 20480) -32768 32767)))
  (def hi (floor (/ p 256)))
  (* (peek om_lut_f_high hi 0) (peek om_lut_f_low (- p (* hi 256)) 0)))

; lut_sine at a phase in cycles (wrapped), linear interpolation (4096).
(defmacro om-sine (phase)
  (def x (* (el-wrap phase) 4096))
  (def i (floor x))
  (def a (peek om_lut_sine i 0))
  (def b (peek om_lut_sine (+ i 1) 0))
  (+ a (* (- b a) (- x i))))

; FmOscillator::SineFm. The phase offset is uint32(fm * 2^31); the float to
; unsigned conversion saturates on the module's ARM core (negative -> 0).
(defmacro om-sine-fm (phase fm)
  (om-sine (+ phase (* 0.5 (clip fm 0 1.9999999)))))

'''


def osc_macro(coefs):
    out = []
    out.append(r'''; One FM oscillator (FmOscillator::Process) at 8x, IIR + FIR decimated.
; midi = carrier note (already -36: the 8x rate), ratio / feedback / amount as
; passed by OminousVoice. Returns one host-rate sample.
(defmacro om-osc (midi ratio feedback amount)
  (make-history h_pc)
  (make-history h_pm)
  (make-history h_prev)
  (make-history h_fma)
  (make-history h_fmi)
  (def rq (el-hold (el-lut om_lut_fm_quantizer ratio 128)))
  (def inc_c (el-hold (* kr (om-midi-to-f midi))))
  (def inc_m (el-hold (* kr (om-midi-to-f (+ midi rq)))))
  (def bright (+ midi (* rq 0.75) -60 (* feedback 24)))
  (def att (el-hold (gswitch (lte bright 0) 1 (max (- 1 (* bright bright 0.0015)) 0))))
  ; fm_amount ramps to `amount` over the block's 8 x blk oversampled steps
  (def fm0 (read-history h_fma))
  (def fmi (gswitch bstart (/ (- amount fm0) (* 8 blk)) (read-history h_fmi)))
  (write-history h_fmi fmi)
  (def pc0 (read-history h_pc))
  (def pm0 (read-history h_pm))
  (def prev0 (read-history h_prev))
  ; NaiveSvf low-pass (f = 2 sin(pi 0.1), damp 2), chained across the 8 steps
  (make-history h_ilp)
  (make-history h_ibp)
  (def ilp_s (read-history h_ilp))
  (def ibp_s (read-history h_ibp))
''')
    for j in range(8):
        prev = "prev0" if j == 0 else f"o{j-1}"
        out.append(f"  (def fa{j} (+ fm0 (* fmi {j + 1})))\n")
        out.append(f"  (def fmod{j} (om-sine-fm (+ pm0 (* inc_m {j + 1})) (* feedback {prev})))\n")
        out.append(f"  (def o{j} (om-sine-fm (+ pc0 (* inc_c {j + 1})) (* att fmod{j} fa{j})))\n")
        plp = "ilp_s" if j == 0 else f"lp{j-1}"
        pbp = "ibp_s" if j == 0 else f"bp{j-1}"
        out.append(f"  (def lp{j} (+ {plp} (* 0.618034 {pbp})))\n")
        out.append(f"  (def bp{j} (+ {pbp} (* 0.618034 (- o{j} (* {pbp} 2) lp{j}))))\n")
        out.append(f"  (def l{j} lp{j})\n")
    out.append("  (write-history h_pc (el-wrap (+ pc0 (* inc_c 8))))\n")
    out.append("  (write-history h_pm (el-wrap (+ pm0 (* inc_m 8))))\n")
    out.append("  (write-history h_prev o7)\n")
    out.append("  (write-history h_ilp lp7)\n")
    out.append("  (write-history h_ibp bp7)\n")
    out.append("  (write-history h_fma (+ fm0 (* fmi 8)))\n")
    # polyphase partial sums: P_k = sum_j c[8k + 7 - j] * l_j
    nk = (len(coefs) + 7) // 8
    for k in range(nk):
        terms = []
        for j in range(8):
            i = 8 * k + 7 - j
            if i < len(coefs):
                terms.append(f"(* {coefs[i]!r} l{j})")
        out.append(f"  (def p{k} (+ {' '.join(terms)}{' 0' if len(terms) == 1 else ''}))\n")
    # transposed chain: t_k(n) = P_k(n) + t_{k+1}(n-1)
    for k in range(1, nk):
        out.append(f"  (make-history h_t{k})\n")
    for k in range(nk - 1, -1, -1):
        if k == nk - 1:
            out.append(f"  (def t{k} p{k})\n")
        else:
            out.append(f"  (def t{k} (+ p{k} (read-history h_t{k + 1})))\n")
    for k in range(1, nk):
        out.append(f"  (write-history h_t{k} t{k})\n")
    out.append("  t0)\n\n")
    return "".join(out)


BODY = r'''; Spatializer (fixed position -0.7 / 0.7): rotating pan with a "behind"
; low-pass; returns (tuple center sides) contributions.
(defmacro om-spatializer (src fixed rotation distance)
  (make-history h_angle)
  (make-history h_l)
  (make-history h_r)
  (def angle0 (read-history h_angle))
  (def angle (gswitch bstart (el-wrap (+ angle0 rotation)) angle0))
  (write-history h_angle angle)
  (def x0 (* distance (om-sine angle)))
  (def y (* distance (om-sine (+ angle 0.25))))
  (def backfront (el-hold (* (+ 1 y) 0.5 distance)))
  (def xx (+ x0 (* fixed (- 1 distance))))
  (def tl (el-hold (om-sine (* (+ 1 xx) 0.125))))
  (def tr (el-hold (om-sine (* (+ 3 xx) 0.125))))
  (def l (el-interp tl 0))
  (def r (el-interp tr 0))
  (make-history h_blp)
  (make-history h_bbp)
  (def bf (el-hold (* 2 (sin (* 3.14159265 0.05 kr)))))
  (def blp0 (read-history h_blp))
  (def bbp0 (read-history h_bbp))
  (def blp (+ blp0 (* bf bbp0)))
  (def bhp (- (- src bbp0) blp))
  (write-history h_blp blp)
  (write-history h_bbp (+ bbp0 (* bf bhp)))
  (def yy (+ src (* backfront (- blp src))))
  (def ll (* l yy))
  (def rr (* r yy))
  (tuple (* (+ ll rr) 0.5) (/ (* (- ll rr) 0.5) 0.7)))

; Multimode SVF (Svf::ProcessMultimode): geometry morphs LP -> HP -> BP.
(defmacro om-filter (x g r mode)
  (def h (el-hold (el-svf-h g r)))
  (def (lp bp hp) (el-svf x g r h))
  (def hpg (el-hold (gswitch (lt mode 0.5) (* mode -2) (+ -2 (* mode 2)))))
  (def lpg (el-hold (gswitch (lt mode 0.5) (- 1 (* mode 2)) 0)))
  (def bpg (el-hold (gswitch (lt mode 0.5) 0 (- (* mode 2) 1))))
  (+ (* hpg hp) (* bpg bp) (* lpg lp)))

(defmacro el-ominous (rising falling gate_f midi strength contour bow_level bow_timbre
                      blow_level blow_meta blow_timbre strike_level strike_meta strike_timbre
                      signature geometry brightness damping position mod_offset)
  ; envelope (ConfigureEnvelope: no attack)
  (def env_a 0)
  (def env_dr (gswitch (lt contour 0.4) (* (+ (* contour 0.625) 0.2) 1.8)
                (gswitch (lt contour 0.6) 0.8 (* (+ (* (- 1 contour) 0.75) 0.15) 1.8))))
  (def env_s (gswitch (lt contour 0.4) 0 (gswitch (lt contour 0.6) (* (- contour 0.4) 5) 1)))
  (def env (el-envelope rising falling gate_f env_a env_dr env_s))
  (def level (el-hold (+ env (gswitch (gte strength 0.5) (- (* 2 strength) 1) 0))))
  ; per-block smoothers (damping_, feedback_; both start at 0)
  (make-history h_damp)
  (make-history h_fb)
  (def damp0 (read-history h_damp))
  (def damp (gswitch bstart (+ damp0 (* (el-coef-block 0.1) (- damping damp0))) damp0))
  (write-history h_damp damp)
  (def fb0 (read-history h_fb))
  (def fb (gswitch bstart (+ fb0 (* (el-coef-block 0.01) (- bow_timbre fb0))) fb0))
  (write-history h_fb fb)
  (def fea (el-hold (gswitch (lte damp 0.9) (* 1.1 damp) 0.99)))
  (def vea (el-hold (+ 1 (* damp damp damp damp 0.5))))
  (def cutoff_midi (+ 12 (* brightness 140) (* fea level 120) (* 0.5 (- midi 64))))
  (def cutoff (om-midi-to-f (max cutoff_midi -12)))
  (def q_bump (- geometry 0.6))
  (def q (el-hold (- 1.72 (* q_bump q_bump 2))))
  (def g1 (el-hold (el-g-host (el-tan-fast cutoff))))
  (def g2 (el-hold (el-g-host (el-tan-fast (* cutoff (+ 1 mod_offset))))))
  (def osc_midi (- midi 36))
  (def fbk (el-hold (* fb (+ 0.25 (* 0.15 signature)))))
  (def amt_scale (el-hold (- 2 (* signature fb))))
  (def detune (el-hold (el-lut om_lut_detune_quantizer bow_level 64)))
  (def o1 (om-osc (el-hold osc_midi) blow_meta fbk (* amt_scale blow_timbre)))
  (def o2 (om-osc (el-hold (+ osc_midi detune)) strike_meta fbk (* amt_scale strike_timbre)))
  ; level smoothing (per sample, 0.01) and raw out
  (make-history h_lv1)
  (make-history h_lv2)
  (def lv1 (+ (read-history h_lv1) (* (el-coef 0.01) (- blow_level (read-history h_lv1)))))
  (def lv2 (+ (read-history h_lv2) (* (el-coef 0.01) (- strike_level (read-history h_lv2)))))
  (write-history h_lv1 lv1)
  (write-history h_lv2 lv2)
  (def x1 (* o1 lv1))
  (def x2 (* o2 lv2))
  (def raw (+ x1 x2))
  ; filters, VCA (level ramps across the block from the previous level)
  (def f1 (om-filter x1 g1 (/ 1 q) geometry))
  (def f2 (om-filter x2 g2 (/ 1 (* q 1.25)) geometry))
  (make-history h_lvl)
  (def lvl_prev (el-hold (read-history h_lvl)))
  (write-history h_lvl (gswitch bstart level (read-history h_lvl)))
  (def lramp (+ lvl_prev (* (- level lvl_prev) (/ bphase blk))))
  (def gain (min (* lramp vea) 1))
  ; spatializers
  (def rot (el-hold (* position position 0.001 tb)))
  (def dist (el-hold (* position (- 2 position))))
  (def (c1 s1) (om-spatializer (* f1 gain) -0.7 rot dist))
  (def (c2 s2) (om-spatializer (* f2 gain) 0.7 (* rot 1.123456) dist))
  (tuple raw (+ c1 c2) (+ s1 s2)))
'''


def macro(path, name):
    """The text of (defmacro name ...) in src/<path>."""
    src = open(os.path.join(ROOT, "src", path)).read()
    i = src.index(f"(defmacro {name} ")
    depth = 0
    for j in range(i, len(src)):
        depth += {"(": 1, ")": -1}.get(src[j], 0)
        if depth == 0:
            return src[i:j + 1]


# Value of `x` on the first sample of each of this voice's blocks (a history
# hold: see el-hold-on in lib.lisp for why not el-hold inside a gate).
OM_HOLD = """(defmacro om-hold (x)
  (el-hold-on x bstart_o))

"""


def own_clock(text):
    return text.replace("bstart", "bstart_o").replace("bphase", "bphase_o")


def main():
    coefs = coefficients()
    # The voice runs inside a block-gate and keeps its own block clock
    # (bstart_o / bphase_o) and copies of the block-clocked helpers, so the
    # gate owns everything the voice runs.
    helpers = ["; Block-clocked helpers on this voice's own clock (bstart_o).\n"]
    helpers.append(OM_HOLD)
    for path, name in (("lib.lisp", "el-interp"), ("envelope.lisp", "el-envelope")):
        helpers.append(own_clock(macro(path, name)).replace(f"(defmacro {name} ", f"(defmacro om-{name[3:]} ") + "\n\n")
    body = own_clock(osc_macro(coefs) + BODY).replace("(el-hold", "(om-hold").replace("(el-interp", "(om-interp") \
        .replace("(el-envelope", "(om-envelope")
    with open(os.path.join(ROOT, "src", "ominous.lisp"), "w") as f:
        f.write(HEAD + "".join(helpers) + body)


if __name__ == "__main__":
    main()

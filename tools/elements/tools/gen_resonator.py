#!/usr/bin/env python3
"""Writes src/resonator.lisp: the modal resonator as scalar code, its 52
modes and 8 bowed modes unrolled. Scalar state can sit in a block-gate (the
voice runs the resonator only while the modal model is selected), and
ComputeFilters runs in a sample-gate on the block's first sample, its
coefficients held in histories between blocks."""
import os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
N = 52
NB = 8
# Resonator::ComputeFilters refreshes modes 0..24 on every block, the higher
# ones on alternate blocks.
ALWAYS = 24

HEAD = r'''; ======================================================================
; Modal resonator (elements/dsp/resonator.cc): 52 band-pass SVF modes
; (Voice sets resolution 52), stretched by lut_stiffness, Q falling with the
; mode index; plus 8 "banded waveguide" bowed modes (delay line + band-pass)
; driven through the bow friction table. The pickup position and the
; LFO-swept side position weight the modes with cosine combs.
; Scalar code, every mode unrolled: ComputeFilters is latched once per
; block (modes above 24 on alternate blocks, as the module does), and the
; voice can gate the whole resonator off while another model plays.
; Inputs: `f` (cycles per 32 kHz sample), geometry, brightness, damping,
; position (block values), mod_freq (LFO cycles per 32 kHz sample),
; mod_offset; per sample: `in` (raw excitation), bow_strength.
; Returns (tuple center sides).
; Host-rate rules: mode cut-offs and Qs are decided at 32 kHz; each SVF gets
; the analog response of its 32 kHz twin (el-g-host); the bowed delay lines
; hold one period at the host rate.
; Generated by tools/gen_resonator.py -- edit that, not this file.
; ======================================================================
(def res_lut_stiffness (tensor @shape [257 1] @file "lut_stiffness.json"))
(def res_lut_4_decades (tensor @shape [257 1] @file "lut_4_decades.json"))

; CosineOscillator APPROXIMATE coefficient for `frequency` (2 cos(2 pi f),
; approximated); its k-th Next() is 0.5 + 0.5 cos(k acos(c / 2)).
(defmacro res-cos-coef (frequency)
  (def x (- frequency 0.25))
  (def neg (lt x 0))
  (def big (gt x 0.5))
  (def fr (gswitch neg (- x) (gswitch big (- x 0.5) x)))
  (def sgn (gswitch neg 16 (gswitch big 16 -16)))
  (* sgn fr (- 1 (* 2 fr))))

; Bow friction table (Resonator::BowTable).
(defmacro res-bow-table (x velocity)
  (def xx (- (* 0.13 velocity) x))
  (def b0 (+ (abs (* xx 6)) 0.75))
  (def b2 (* b0 b0))
  (def b4 (* b2 b2))
  (* xx (clip (/ 0.25 b4) 0.0025 0.245)))

; One band-pass mode (stmlib Svf), `rg` = r + g. State holds while `on` is 0
; (modes past num_modes are not processed). Returns the band-pass output.
(defmacro res-mode (x g rg h on)
  (make-history s1)
  (make-history s2)
  (def st1 (read-history s1))
  (def st2 (read-history s2))
  (def hp (* (- x (* rg st1) st2) h))
  (def bp (+ (* g hp) st1))
  (def lp (+ (* g bp) st2))
  (write-history s1 (gswitch on (+ (* g hp) bp) st1))
  (write-history s2 (gswitch on (+ (* g bp) lp) st2))
  (* on bp))

; One bowed mode: a delay line of `period` samples closed through a
; normalized band-pass (g, r, h). Returns (tuple read out): the delay read
; (x0.99) and the band-pass output written back into the line.
(defmacro res-bowed (input period g r h on)
  (make-history hs)
  (def rd (* 0.99 (delay (read-history hs) (- period 1) @max-delay 4096)))
  (def (lp bp hp) (el-svf (* on (+ input rd)) g r h))
  (def s (* on bp r))
  (write-history hs s)
  (tuple rd s))

; Bowed delay: floor(1 / f) samples at the host rate, halved until it is
; shorter than the 1024-sample line (in 32 kHz samples).
(defmacro res-period (pf)
  (def p0 (floor (/ 1 (* pf kr))))
  (def lim (/ 1024 kr))
  (def p1 (gswitch (gte p0 lim) (floor (* p0 0.5)) p0))
  (def p2 (gswitch (gte p1 lim) (floor (* p1 0.5)) p1))
  (gswitch (gte p2 lim) (floor (* p2 0.5)) p2))

(defmacro el-resonator (f geometry brightness damping position mod_freq mod_offset in bow_strength)
  ; Modes above 24 refresh on alternate blocks (clock_divider_); the first
  ; block sets them all.
  (make-history h_cd)
  (make-history h_started)
  (def cd (+ (read-history h_cd) bstart))
  (write-history h_cd cd)
  (def first (- 1 (read-history h_started)))
  (write-history h_started 1)
  (def cd_par (el-imod cd 2))
  (def upd_odd (max first (eq cd_par 0)))
  (def upd_even (max first (eq cd_par 1)))
  ; Coefficients hold between blocks in histories.
HISTS
  ; ---- ComputeFilters, on the first sample of each block only
  (def (COEFS)
    (sample-gate bstart (do
  (def stiffness (el-lut res_lut_stiffness geometry 256))
  (def sk (gswitch (lt stiffness 0) 0.93 0.98))
  (def q0 (* 500 (el-lut res_lut_4_decades (* damping 0.8) 256)))
  (def ba1 (- 1 geometry))
  (def ba2 (* ba1 ba1))
  (def ba4 (* ba2 ba2))
  (def bright (* brightness (- 1 (* 0.2 ba4 ba4))))
  (def ql0 (+ (* bright (- 2 bright) 0.85) 0.15))
  (def qrate (* geometry (- 2 geometry) 0.1))
  ; per mode: harmonic, stretch and Q accumulate as in the C++ loop
  (def harm_0 f)
  (def sf_0 1)
  (def st_0 stiffness)
  (def ql_0 ql0)
  (def q_0 q0)
  (def nm_m 0)
'''

MODE = '''  (def pfr_{i} (* harm_{i} sf_{i}))
  (def pf_{i} (min pfr_{i} 0.49))
  (def nm_{i} (gswitch (lt pfr_{i} 0.49) {n} nm_{p}))
  (def gn_{i} (el-g-host (el-tan-fast pf_{i})))
  (def rn_{i} (/ 1 (+ 1 (* pf_{i} q_{i}))))
{refresh}'''
NEXT = '''  (def harm_{n} (+ harm_{i} f))
  (def sf_{n} (+ sf_{i} st_{i}))
  (def st_{n} (* st_{i} sk))
  (def ql_{n} (+ ql_{i} (* qrate (- 1 ql_{i}))))
  (def q_{n} (* q_{i} ql_{n}))
'''
BOWED_COEF = '''  (def brn_{i} (/ 1 (+ 1 (* pf_{i} 1500))))
  (def bhn_{i} (el-svf-h gn_{i} brn_{i}))
  (def bpern_{i} (res-period pf_{i}))
'''
# Modes refreshed every block use the block's values; the others latch them
# on their alternate-block clock.
EVERY = '''  (def gu_{i} gn_{i})
  (def rgu_{i} (+ rn_{i} gn_{i}))
  (def hu_{i} (el-svf-h gn_{i} rn_{i}))
'''
DIVIDED = '''  (def gu_{i} (gswitch {upd} gn_{i} (read-history hg_{i})))
  (def rgu_{i} (gswitch {upd} (+ rn_{i} gn_{i}) (read-history hrg_{i})))
  (def hu_{i} (gswitch {upd} (el-svf-h gn_{i} rn_{i}) (read-history hh_{i})))
'''
# A coefficient: the gate's value on the block's first sample, then the
# history the gate wrote (only the gate writes it).
HOLD = '''  (def {name} (gswitch bstart c{name} (read-history h{name})))
'''

SAMPLE = r'''  (def nwg (min num_modes 8))
  ; ---- per-sample pickup combs: CosineOscillator recurrences
  (make-history h_lfo)
  (def lfo_ph (el-wrap (+ (read-history h_lfo) (* mod_freq kr))))
  (write-history h_lfo lfo_ph)
  (def lfo (gswitch (gt lfo_ph 0.5) (- 1 lfo_ph) lfo_ph))
  (def pos (el-interp position 0))
  (def c_main (res-cos-coef pos))
  (def c_aux (res-cos-coef (+ mod_offset lfo)))
  (def a_0 0.5)
  (def a_1 (- (* c_main a_0) (* c_main 0.25)))
  (def x_0 0.5)
  (def x_1 (- (* c_aux x_0) (* c_aux 0.25)))
'''


# (value computed in the gate, held name): every mode's g, r + g and h, the
# bowed modes' r, h and delay, and the number of modes.
COEFS = ([(f"{a}_{i}", f"{b}_{i}") for i in range(N) for a, b in (("gu", "g"), ("rgu", "rg"), ("hu", "h"))]
         + [(f"{a}_{i}", f"{b}_{i}") for i in range(NB) for a, b in (("brn", "br"), ("bhn", "bh"), ("bpern", "bper"))]
         + [(f"nm_{N - 1}", "num_modes")])


def main():
    hists = "".join(f"  (make-history h{held})\n" for _, held in COEFS)
    out = [HEAD.replace("HISTS\n", hists).replace("COEFS", " ".join(f"c{held}" for _, held in COEFS))]
    for i in range(N):
        refresh = EVERY.format(i=i) if i <= ALWAYS else DIVIDED.format(i=i, upd="upd_odd" if i % 2 else "upd_even")
        out.append(MODE.format(i=i, n=i + 1, p=i - 1 if i else "m", refresh=refresh))
        if i < NB:
            out.append(BOWED_COEF.format(i=i))
        if i + 1 < N:
            step = NEXT.format(i=i, n=i + 1)
            if i + 2 == N:  # the last mode needs no next stiffness
                step = "".join(l + "\n" for l in step.splitlines() if f"(def st_{i + 1} " not in l)
            out.append(step)
    out.extend(f"  (write-history h{held} {value})\n" for value, held in COEFS)
    out.append("  (tuple " + " ".join(value for value, _ in COEFS) + "))))\n")
    # (the bowed periods are read from their histories directly, below)
    out.extend(HOLD.format(name=held) for _, held in COEFS if not held.startswith("bper_"))
    out.append(SAMPLE)
    # Mode by mode, each with its comb weights and running sums, so every
    # mode's values die before the next mode starts (fewer register spills).
    out.append("  ; ---- 52 modes\n  (def x (* in 0.125))\n  (def sc_m 0)\n  (def ss_m 0)\n")
    for i in range(N):
        if i >= 2:
            out.append(f"  (def a_{i} (- (* c_main a_{i - 1}) a_{i - 2}))\n")
            out.append(f"  (def x_{i} (- (* c_aux x_{i - 1}) x_{i - 2}))\n")
        p = i - 1 if i else "m"
        out.append(f"  (def s_{i} (res-mode x g_{i} rg_{i} h_{i} (lt {i} num_modes)))\n")
        out.append(f"  (def sc_{i} (+ sc_{p} (* s_{i} (+ a_{i} 0.5))))\n")
        out.append(f"  (def ss_{i} (+ ss_{p} (* s_{i} (+ x_{i} 0.5))))\n")
    out.append(f"  (def sum_center sc_{N - 1})\n  (def sum_side ss_{N - 1})\n")
    out.append("  ; ---- 8 bowed modes\n  (make-history h_bow)\n  (def bin (+ x (read-history h_bow)))\n")
    for i in range(NB):
        # The period comes straight from its history, never from the gate's
        # value (a delay whose time comes out of a gate runs ungated), so a
        # new period takes effect one sample into the block; before the
        # first block it is 0, a zero-sample delay.
        out.append(f"  (def (rd_{i} bo_{i}) (res-bowed bin (read-history hbper_{i}) g_{i} br_{i} bh_{i} (lt {i} nwg)))\n")
    out.append("  (def bow_sum (+ " + " ".join(f"rd_{i}" for i in range(NB)) + "))\n")
    out.append("  (write-history h_bow (res-bow-table bow_sum bow_strength))\n")
    out.append("  (def bowed (* 8 (+ " + " ".join(f"(* bo_{i} (+ a_{i} 0.5))" for i in range(NB)) + ")))\n")
    out.append("  (tuple (+ sum_center bowed) (- sum_side sum_center)))\n")
    with open(os.path.join(ROOT, "src", "resonator.lisp"), "w") as f:
        f.write("".join(out))


if __name__ == "__main__":
    main()
